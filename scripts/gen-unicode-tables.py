#!/usr/bin/env python3
"""Generate our wide-character tables from pinned Unicode 17.0.0 UCD data.

Classification is a locale policy: digits and hex digits stay ASCII as required
by ISO C, alphabetic and casing use UCD derived properties, and printable
characters are assigned letters, marks, numbers, punctuation, symbols, spaces
and private-use characters. No libc implementation is an input.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'vendor/unicode'


def properties(name):
    result = {}
    for line in (DATA / name).read_text().splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        fields = line.split(';')
        bounds, prop = fields[0].strip(), fields[1].strip()
        pair = bounds.split('..')
        lo, hi = int(pair[0], 16), int(pair[-1], 16)
        result.setdefault(prop, set()).update(range(lo, hi + 1))
    return result


def generate():
    category = ['Cn'] * 0x110000
    upper, lower = {}, {}
    first = None
    for line in (DATA / 'UnicodeData.txt').read_text().splitlines():
        f = line.split(';')
        cp = int(f[0], 16)
        if f[1].endswith(', First>'):
            first = cp
        elif f[1].endswith(', Last>'):
            category[first:cp + 1] = [f[2]] * (cp + 1 - first)
            first = None
        else:
            category[cp] = f[2]
        if f[12]:
            upper[cp] = int(f[12], 16)
        if f[13]:
            lower[cp] = int(f[13], 16)
    derived = properties('DerivedCoreProperties.txt')
    spaces = properties('PropList.txt')['White_Space']
    masks = []
    for cp, cat in enumerate(category):
        alpha = cp in derived['Alphabetic']
        digit = 48 <= cp <= 57
        space = cp in spaces
        printable = cat[0] in 'LMNPSZ' or cat == 'Co'
        graph = printable and not space
        predicates = (alpha or digit, alpha, cat == 'Zs' or cp == 9,
                      cat == 'Cc', digit, graph, cp in derived['Lowercase'],
                      printable, graph and not alpha and not digit, space,
                      cp in derived['Uppercase'], digit or 65 <= cp <= 70 or 97 <= cp <= 102)
        masks.append(sum(1 << i for i, flag in enumerate(predicates) if flag))
    ranges = []
    start = 0
    for cp in range(1, len(masks) + 1):
        if cp == len(masks) or masks[cp] != masks[start]:
            if masks[start]:
                ranges.append((start, cp - 1, masks[start]))
            start = cp
    text = '// Generated by scripts/gen-unicode-tables.py; Unicode 17.0.0.\n'
    text += 'pub(super) static CLASSES: &[(u32, u32, u16)] = &[\n'
    text += ''.join(f'    (0x{lo:x}, 0x{hi:x}, 0x{mask:x}),\n' for lo, hi, mask in ranges)
    text += '];\n'
    for name, table in [('UPPER', upper), ('LOWER', lower)]:
        text += f'pub(super) static {name}: &[(u32, u32)] = &[\n'
        text += ''.join(f'    (0x{cp:x}, 0x{dest:x}),\n' for cp, dest in sorted(table.items()))
        text += '];\n'
    (ROOT / 'libs/libbreenix-libc/src/locale/unicode_tables.rs').write_text(text)


if __name__ == '__main__':
    generate()
