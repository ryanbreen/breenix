#!/usr/bin/env python3
"""Write the BreenGL suite's literal ARM64 boot-ribbon stages (docs/gui/breengel.md section 23.7).

The list is every ARM64-applicable stage in docs/boot-path.json, in that file's order: a
named stage takes its marker from the ARM64 stage catalog, and an inline stage gives its
own marker. The suite compares the kernel's ribbon records against this file, so it is
generated from the manifest here, independently of the kernel's build-time loader, and is
never edited by hand.

    scripts/gen-stage-boot-markers.py           # rewrite the file
    scripts/gen-stage-boot-markers.py --check   # exit 1 if the file is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs/boot-path.json"
CATALOG = ROOT / "tools/breenix-runs/Sources/BreenixRuns/Resources/boot-stages-aarch64.json"
OUT = ROOT / "userspace/programs/src/suite_breengel/stage_boot_markers.in"


def rust_string(text):
    out = []
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif " " <= ch <= "~" or ord(ch) > 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return '"' + "".join(out) + '"'


def markers():
    catalog = {s["name"]: s["marker"] for s in json.loads(CATALOG.read_text())["stages"]}
    found = []
    for milestone in json.loads(MANIFEST.read_text())["milestones"]:
        for stage in milestone["stages"].get("aarch64", []):
            if isinstance(stage, str):
                if stage not in catalog:
                    sys.exit(f"{milestone['id']}: stage {stage!r} is not in the ARM64 catalog")
                found.append(catalog[stage])
            elif "marker" in stage:
                found.append(stage["marker"])
            else:
                sys.exit(f"{milestone['id']}: an ARM64 stage has no marker")
    return found


def render(found):
    lines = [
        "// Literal ARM64 stage expectations from docs/boot-path.json and its committed catalog.",
        "// Independent of the kernel marker loader and ribbon renderer.",
        "// Generated by scripts/gen-stage-boot-markers.py; do not edit.",
        "&[",
    ]
    lines += [f"    {rust_string(m)}," for m in found]
    lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    text = render(markers())
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen-stage-boot-markers.py")
        return
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
