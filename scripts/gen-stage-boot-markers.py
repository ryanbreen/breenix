#!/usr/bin/env python3
"""Write the BreenGL suite's literal boot-ribbon stages (docs/gui/breengel.md section 23.7).

Each list follows its architecture manifest in order: a named stage takes its marker from
the corresponding catalog, an inline stage gives its own marker, and metal host-only
stages are skipped. The suite compares the kernel's ribbon records against this file, so it is
generated from the manifest here, independently of the kernel's build-time loader, and is
never edited by hand.

    scripts/gen-stage-boot-markers.py           # rewrite the files
    scripts/gen-stage-boot-markers.py --check   # exit 1 if a file is missing or stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "docs/boot-path.json"
CATALOG = ROOT / "tools/breenix-runs/Sources/BreenixRuns/Resources/boot-stages-aarch64.json"
OUT = ROOT / "userspace/programs/src/suite_breengel/stage_boot_markers.in"


def rust_string(text):
    out = []
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif " " <= ch <= "~" or ord(ch) > 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return '"' + "".join(out) + '"'


def markers(manifest=MANIFEST, catalog_path=CATALOG, arch="aarch64"):
    catalog = {s["name"]: s["marker"] for s in json.loads(catalog_path.read_text())["stages"]}
    found = []
    for milestone in json.loads(manifest.read_text())["milestones"]:
        for stage in milestone["stages"].get(arch, []):
            if isinstance(stage, str):
                if stage not in catalog:
                    sys.exit(f"{milestone['id']}: stage {stage!r} is not in the {arch} catalog")
                found.append(catalog[stage])
            elif "marker" in stage:
                found.append(stage["marker"])
            elif "host" in stage and arch == "x86_64":
                continue
            else:
                sys.exit(f"{milestone['id']}: an {arch} stage has no marker")
    return found


def render(found, arch="ARM64", manifest="docs/boot-path.json"):
    lines = [
        f"// Literal {arch} stage expectations from {manifest} and its committed catalog.",
        "// Independent of the kernel marker loader and ribbon renderer.",
        "// Generated by scripts/gen-stage-boot-markers.py; do not edit.",
        "&[",
    ]
    lines += [f"    {rust_string(m)}," for m in found]
    lines.append("]")
    return "\n".join(lines) + "\n"


def main():
    metal_manifest = ROOT / "docs/metal/boot-path.json"
    metal_catalog = ROOT / "tools/breenix-runs/Sources/BreenixRuns/Resources/boot-stages-x86_64.json"
    metal_out = ROOT / "userspace/programs/src/suite_breengel/stage_boot_markers_x86_64.in"
    outputs = [(OUT, render(markers())),
               (metal_out, render(markers(metal_manifest, metal_catalog, "x86_64"),
                                  "x86_64", "docs/metal/boot-path.json"))]
    for out, text in outputs:
        if "--check" in sys.argv[1:]:
            if not out.is_file() or out.read_text(encoding="utf-8") != text:
                sys.exit(f"{out.relative_to(ROOT)} is missing or stale: run scripts/gen-stage-boot-markers.py")
        else:
            out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
