#!/usr/bin/env python3
"""Generate libs/libbreenix-libc/src/math/consts.rs: the constants Breenix's libm needs.

Every value is derived here from its mathematical definition with exact integer and
rational arithmetic; nothing is copied from a table:

  pi        Machin's formula, pi = 16 atan(1/5) - 4 atan(1/239)
  ln 2      2 atanh(1/3);  ln 10 = 3 ln 2 + 2 atanh(1/9)  (since 10/8 = (1 + 1/9)/(1 - 1/9))
  sqrt(pi)  the integer square root of pi scaled by 2^(2 BITS)
  B_2k      Bernoulli numbers from sum_{j=0}^{m} C(m+1, j) B_j = 0
  gamma     Euler's constant by Euler-Maclaurin summation:
            gamma = H_n - ln n - 1/(2n) + sum_k B_2k / (2k n^2k), with n = 10^4
  1/n!, 1/(2k+1)  exact rationals

Each constant is written as a double-double (hi, lo): hi is the double nearest the value
and lo the double nearest the remainder, both as exact bit patterns.

Usage: scripts/libm-coeffs.py [output path]
"""
from fractions import Fraction
import math
import struct
import sys

BITS = 1600  # fixed-point fraction bits for the series; far beyond what any output needs
ONE = 1 << BITS


def atan_inv(n):
    """atan(1/n) in fixed point."""
    total, term, k, sign = 0, ONE // n, 1, 1
    n2 = n * n
    while term:
        total += sign * (term // k)
        term //= n2
        k += 2
        sign = -sign
    return total


def atanh_inv(n):
    """atanh(1/n) in fixed point."""
    total, term, k = 0, ONE // n, 1
    n2 = n * n
    while term:
        total += term // k
        term //= n2
        k += 2
    return total


PI = 16 * atan_inv(5) - 4 * atan_inv(239)
LN2 = 2 * atanh_inv(3)
LN10 = 3 * LN2 + 2 * atanh_inv(9)
SQRT_PI = math.isqrt(PI << BITS)


def frac(fixed):
    return Fraction(fixed, ONE)


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def dd(value):
    hi = float(value)  # Fraction -> float rounds to nearest
    lo = float(value - Fraction(hi))
    return hi, lo


def bernoulli(n):
    b = [Fraction(1)]
    for m in range(1, n + 1):
        acc = sum(math.comb(m + 1, j) * b[j] for j in range(m))
        b.append(-acc / (m + 1))
    return b


def emit_dd(out, name, value, doc):
    hi, lo = dd(value)
    out.append(f"/// {doc}")
    out.append(f"pub(crate) const {name}: DD = DD::new(f64::from_bits(0x{bits(hi):016x}), "
               f"f64::from_bits(0x{bits(lo):016x}));")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "libs/libbreenix-libc/src/math/consts.rs"
    pi = frac(PI)
    ln2 = frac(LN2)
    ln10 = frac(LN10)
    sqrt_pi = frac(SQRT_PI)
    out = [
        "//! Generated by scripts/libm-coeffs.py; do not edit. Each constant is derived there",
        "//! from its definition with exact arithmetic.",
        "",
        "use super::dd::DD;",
        "",
    ]
    emit_dd(out, "PI", pi, "pi")
    emit_dd(out, "PI_2", pi / 2, "pi / 2")
    emit_dd(out, "PI_4", pi / 4, "pi / 4")
    emit_dd(out, "LN2", ln2, "ln 2")
    emit_dd(out, "INV_LN2", 1 / ln2, "1 / ln 2")
    emit_dd(out, "INV_LN10", 1 / ln10, "1 / ln 10")
    emit_dd(out, "INV_SQRT_PI", 1 / sqrt_pi, "1 / sqrt(pi)")
    emit_dd(out, "TWO_OVER_SQRT_PI", 2 / sqrt_pi, "2 / sqrt(pi)")
    # ln pi = 2 atanh((pi - 1)/(pi + 1)), summed in fixed point.
    t = ((PI - ONE) << BITS) // (PI + ONE)
    t2 = t * t >> BITS
    ln_pi_fixed, power, k = 0, t, 1
    while power:
        ln_pi_fixed += power // k
        power = power * t2 >> BITS
        k += 2
    ln_pi = 2 * frac(ln_pi_fixed)
    emit_dd(out, "HALF_LN_2PI", (ln2 + ln_pi) / 2, "ln(2 pi) / 2")
    emit_dd(out, "LN_PI", ln_pi, "ln pi")

    # Stirling's series for ln Gamma: sum_k B_2k / (2k (2k - 1) x^(2k - 1)).
    b = bernoulli(40)
    out.append("")
    out.append("/// B_2k / (2k (2k - 1)) for k = 1.., the coefficients of Stirling's series.")
    out.append("pub(crate) const STIRLING: [DD; 18] = [")
    for k in range(1, 19):
        hi, lo = dd(b[2 * k] / (2 * k * (2 * k - 1)))
        out.append(f"    DD::new(f64::from_bits(0x{bits(hi):016x}), f64::from_bits(0x{bits(lo):016x})),")
    out.append("];")

    # Euler's constant.
    n = 10000
    harmonic = sum(ONE // k for k in range(1, n + 1))
    ln_n = 4 * LN10  # ln 10^4
    tail = sum(b[2 * k] / (2 * k * Fraction(n) ** (2 * k)) for k in range(1, 15))
    euler = frac(harmonic - ln_n) - Fraction(1, 2 * n) + tail
    out.append("")
    emit_dd(out, "EULER", euler, "Euler's constant gamma")
    emit_dd(out, "PI_SQ_12", pi * pi / 12, "pi^2 / 12 = zeta(2) / 2")

    out.append("")
    out.append("/// 1 / n! for n = 0..")
    out.append("pub(crate) const INV_FACT: [DD; 36] = [")
    for k in range(36):
        hi, lo = dd(Fraction(1, math.factorial(k)))
        out.append(f"    DD::new(f64::from_bits(0x{bits(hi):016x}), f64::from_bits(0x{bits(lo):016x})),")
    out.append("];")
    out.append("")
    out.append("/// 1 / (2k + 1) for k = 0..")
    out.append("pub(crate) const INV_ODD: [DD; 30] = [")
    for k in range(30):
        hi, lo = dd(Fraction(1, 2 * k + 1))
        out.append(f"    DD::new(f64::from_bits(0x{bits(hi):016x}), f64::from_bits(0x{bits(lo):016x})),")
    out.append("];")

    # 2/pi as a binary fraction: word i holds the bits of weight 2^-(64 i + 1) .. 2^-(64 i + 64).
    words = 20
    two_over_pi = (2 << (64 * words + BITS)) // PI
    out.append("")
    out.append("/// The binary expansion of 2/pi, most significant bits first: word i holds the bits")
    out.append("/// of weight 2^-(64 i + 1) through 2^-(64 i + 64).")
    out.append(f"pub(crate) const TWO_OVER_PI: [u64; {words}] = [")
    for i in range(words):
        w = (two_over_pi >> (64 * (words - 1 - i))) & ((1 << 64) - 1)
        out.append(f"    0x{w:016x},")
    out.append("];")
    out.append("")
    with open(path, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
