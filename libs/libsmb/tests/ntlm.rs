use libsmb::auth::ntlm::{ntowfv2, ntlmv2_response};

#[test]
fn microsoft_ntlmv2_worked_example() {
    let key = ntowfv2("Password", "User", "Domain");
    assert_eq!(key, [0x0c,0x86,0x8a,0x40,0x3b,0xfd,0x7a,0x93,0xa3,0x00,0x1e,0xf2,0x2e,0xf0,0x2e,0x3f]);
    let target = [2,0,12,0,68,0,111,0,109,0,97,0,105,0,110,0,1,0,12,0,83,0,101,0,114,0,118,0,101,0,114,0,0,0,0,0];
    let (response, session_key) = ntlmv2_response(&key, [1,0x23,0x45,0x67,0x89,0xab,0xcd,0xef], [0xaa; 8], 0, &target);
    assert_eq!(&response[..16], &[0x68,0xcd,0x0a,0xb8,0x51,0xe5,0x1c,0x96,0xaa,0xbc,0x92,0x7b,0xeb,0xef,0x6a,0x1c]);
    assert_eq!(session_key, [0x8d,0xe4,0x0c,0xca,0xdb,0xc1,0x4a,0x82,0xf1,0x5c,0xb0,0xad,0x0d,0xe9,0x5c,0xa3]);
}
