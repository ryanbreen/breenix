/// The text for an error number, without its terminator; None for unknown numbers.
pub(crate) fn error_text(errnum: i32) -> Option<&'static str> {
    error_cstr(errnum).map(|t| &t[..t.len() - 1])
}

/// The text for an error number with its terminator.
pub(super) fn error_cstr(errnum: i32) -> Option<&'static str> {
    // 41 and 58 have no Linux meaning; they are reported as unknown.
    match errnum {
        41 | 58 => None,
        n if n >= 0 && (n as usize) < ERRORS.len() => Some(ERRORS[n as usize]),
        _ => None,
    }
}

