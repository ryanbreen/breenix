#!/usr/bin/env python3
"""Assemble the pinned Falcon sources and compile the shared fixed catalogue."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / "vendor/kepler"
HERE = Path(__file__).resolve().parent


def digest(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, indent=2, sort_keys=True) + "\n").encode()


def run(args, **kwargs):
    result = subprocess.run([str(a) for a in args], capture_output=True, check=True, **kwargs)
    if result.stderr:
        raise RuntimeError(f"unexpected diagnostics from {args[0]}:\n{result.stderr.decode()}")
    return result.stdout


def verify_sources():
    manifest = json.loads((VENDOR / "sources.json").read_text())
    paths = set()
    for entry in manifest["files"]:
        path = VENDOR / entry["project"] / entry["path"]
        paths.add(path)
        if digest(path.read_bytes()) != entry["vendored_sha256"]:
            raise RuntimeError(f"vendored source hash mismatch: {path.relative_to(ROOT)}")
        header = entry["notice"]
        if entry["license"] != "MIT" or not (
            "Permission is hereby granted, free of charge" in header
            or "SPDX-License-Identifier: MIT" in header
        ):
            raise RuntimeError(f"unadmitted source license: {path.relative_to(ROOT)}")
        if not path.read_text().startswith(header):
            raise RuntimeError(f"original license notice changed: {path.relative_to(ROOT)}")
    actual = {p for project in manifest["projects"] for p in (VENDOR / project).rglob("*") if p.is_file()}
    if actual != paths:
        raise RuntimeError(f"unrecorded/missing vendor sources: {actual ^ paths}")
    return manifest


def catalogue():
    # Same text consumed by the ARM backend: do not fork its arithmetic or ABI.
    shared = ROOT / "kernel/src/gpu/virgl"
    result = []
    abi = (ROOT / "libs/gpu-abi/src/lib.rs").read_text().split("pub mod pipeline {", 1)[1].split("pub const PROBE_INT", 1)[0]
    pairs = re.findall(r"pub const ([A-Z_]+): u32 = ([0-9]+);", abi)
    names = {int(ident): name.lower() for name, ident in pairs}
    if set(names) != set(range(16)):
        raise RuntimeError("fixed pipeline identities changed; review the catalogue")
    for ident, name in sorted(names.items()):
        path = shared / "pipelines" / (f"{name}.frag.tgsi" if ident < 2 else f"{ident}.tgsi")
        result.append((f"pipeline-{name}", path, {"pipeline": ident, "name": name}))
    for routine in range(25):
        result.append((f"probe-int-{routine:02}", shared / "profile" / f"r{routine:02}.tgsi",
                       {"name": "probe_int", "pipeline": 16, "routine": routine}))
    result.extend((name, HERE / "shaders" / file, {"name": name}) for name, file in [
        ("catalogue-vertex", "catalogue.vert.tgsi"),
        ("diagnostic-triangle-vertex", "triangle.vert.tgsi"),
        ("diagnostic-triangle-fragment", "triangle.frag.tgsi")])
    controls = ROOT / "tests/fixtures/gt710_shader_controls"
    for name in ("constant-colour-fragment", "drop-colour-vertex"):
        result.append((name, controls / (name + ".tgsi"), {"name": name}))
    return result


def emit_embeddings(output, files):
    rust = ["// Generated by tools/kepler/assets.py; byte assets retain vendor/kepler/NOTICES.",
            "// Architecture neutral; no allocation or host runtime dependency.",
            "pub static ASSETS: &[(&str, &[u8])] = &["]
    c = ["/* Generated by tools/kepler/assets.py; retain vendor/kepler/NOTICES. */",
         "#ifndef BREENIX_KEPLER_ASSETS_H", "#define BREENIX_KEPLER_ASSETS_H", "#include <stddef.h>",
         "struct breenix_kepler_asset { const char *name; const unsigned char *data; size_t size; };"]
    for name in sorted(files):
        rust.append(f'    ("{name}", include_bytes!("{name}")),')
        symbol = "kepler_" + re.sub(r"[^a-zA-Z0-9]", "_", name)
        data = (output / name).read_bytes()
        c.append(f"static const unsigned char {symbol}[] = {{")
        for start in range(0, len(data), 24):
            c.append("    " + ",".join(f"0x{b:02x}" for b in data[start:start+24]) + ",")
        c.append("};")
    rust.append("];\n")
    c.append("static const struct breenix_kepler_asset breenix_kepler_assets[] = {")
    for name in sorted(files):
        symbol = "kepler_" + re.sub(r"[^a-zA-Z0-9]", "_", name)
        c.append(f'    {{"{name}", {symbol}, sizeof({symbol})}},')
    c.extend(["};", "#endif", ""])
    (output / "embed.rs").write_text("\n".join(rust))
    (output / "embed.h").write_text("\n".join(c))


def generate(tools, output, cpp):
    sources = verify_sources()
    output.mkdir(parents=True, exist_ok=True)
    # Refuse stale files: callers build into a new directory, then publish it.
    if list(output.iterdir()):
        raise RuntimeError(f"asset output directory must be empty: {output}")
    version = run([cpp, "-dumpfullversion"]).decode().strip()
    if version != "16.1.0":
        raise RuntimeError(f"firmware requires GNU cpp 16.1.0, got {version}")
    files = {}
    firmware = []
    for entry, name, section in [("hubgk208", "fecs", "grhub"), ("gpcgk208", "gpccs", "grgpc")]:
        text = run([cpp, "-P", "-CC", "-undef", "-nostdinc", VENDOR / "nouveau" / (entry + ".fuc5")]).decode()
        # Falcon macros deliberately use comment newlines as instruction breaks.
        text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m[0].count("\n"), text, flags=re.S)
        preprocessed = output / (name + ".fuc")
        preprocessed.write_text(text)
        assembled = run([tools / "envyas", "-m", "falcon", "-V", "fuc5", "-a", "-w", preprocessed]).decode()
        arrays = dict(re.findall(r"uint32_t\s+(\w+)\[\]\s*=\s*\{(.*?)\};", assembled, re.S))
        expected = {f"gk208_{section}_data", f"gk208_{section}_code"}
        if set(arrays) != expected:
            raise RuntimeError(f"unexpected firmware sections: {set(arrays)}")
        for part in ["code", "data"]:
            body = re.sub(r"/\*.*?\*/", "", arrays[f"gk208_{section}_{part}"], flags=re.S)
            words = [int(s, 16) for s in re.findall(r"0x[0-9a-fA-F]+", body)]
            data = struct.pack("<" + "I" * len(words), *words)
            if not data or (part == "code" and len(data) % 256):
                raise RuntimeError(f"invalid {name} {part} size")
            filename = f"{name}.{part}.bin"
            (output / filename).write_bytes(data)
            files[filename] = {"bytes": len(data), "sha256": digest(data), "license": "MIT"}
        firmware.append({"name": name, "entry_source": f"nouveau/{entry}.fuc5", "falcon": 5,
                         "preprocessed_sha256": digest(text.encode())})
        preprocessed.unlink()
    shaders = []
    for name, path, identity in catalogue():
        run([tools / "kepler-compile", path, output / name])
        meta = json.loads((output / (name + ".json")).read_text())
        if meta["chipset"] != 0x106 or meta["builtin_calls"] != 0 or meta["relocations"] != 0:
            raise RuntimeError(f"invalid target or unresolved code dependency: {name}")
        disassembly = run([tools / "envydis", "-m", "gk110", "-i", "-n", output / (name + ".bin")])
        if re.search(rb"\b(unknown|invalid)\b|\?\?", disassembly, re.I):
            raise RuntimeError(f"undecodable GK110 instruction in {name}")
        (output / (name + ".asm")).write_bytes(disassembly)
        for ext in ["bin", "sph", "json", "asm"]:
            filename = f"{name}.{ext}"
            data = (output / filename).read_bytes()
            if ext == "sph" and len(data) != 80:
                raise RuntimeError(f"wrong SPH size: {name}")
            files[filename] = {"bytes": len(data), "sha256": digest(data),
                               "license": "MIT" if ext == "sph" else "PolyForm-Noncommercial-1.0.0"}
        shaders.append(dict(identity, asset=name, source=str(path.relative_to(ROOT)),
                            source_sha256=digest(path.read_bytes()), metadata=meta))
    (output / "NOTICES").write_bytes((VENDOR / "NOTICES").read_bytes())
    manifest = {"schema": 1, "chipset": 0x106, "byte_order": "little", "sources": sources["projects"],
                "source_lock_sha256": digest((VENDOR / "sources.json").read_bytes()),
                "firmware": firmware, "shaders": shaders, "files": files,
                "host_toolchain": json.loads((tools / "toolchain.json").read_text()),
                "recipe_sha256": {str(p.relative_to(ROOT)): digest(p.read_bytes()) for p in
                                  [HERE / "assets.py", HERE / "compile.cpp", HERE / "CMakeLists.txt",
                                   ROOT / "libs/gpu-abi/src/lib.rs"]},
                "recipe": {"cpp": "GNU cpp 16.1.0 -P -CC -undef -nostdinc", "opt_level": 3,
                           "frontend": "Breenix fixed TGSI to nv50_ir", "helper_library": "forbidden",
                           "auxiliary_constant_buffer_slot": 15, "texture_handle_base_bytes": 0}}
    (output / "manifest.json").write_bytes(json_bytes(manifest))
    emit_embeddings(output, [n for n in files if not n.endswith(".asm")]+["manifest.json"])
    print(f"Generated FECS/GPCCS and {len(shaders)} GK208B shaders in {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify-sources", action="store_true")
    parser.add_argument("--tools", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--cpp", default=os.environ.get("KEPLER_CPP", "cpp-16"))
    args = parser.parse_args()
    if args.verify_sources:
        manifest = verify_sources()
        print(f"Verified {len(manifest['files'])} pinned MIT source files")
    else:
        if not args.tools or not args.output:
            parser.error("--tools and --output are required")
        destination = args.output.resolve()
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory(prefix=".kepler-assets-", dir=destination.parent) as temp:
            staged = Path(temp) / "assets"
            generate(args.tools.resolve(), staged, args.cpp)
            if destination.exists() and not list(destination.iterdir()):
                destination.rmdir()
            if destination.exists():
                previous = json.loads((destination / "manifest.json").read_text())
                known = set(previous["files"]) | {"manifest.json", "embed.rs", "embed.h", "NOTICES"}
                if {p.name for p in destination.iterdir()} != known or any(p.is_dir() for p in destination.iterdir()):
                    raise RuntimeError("refusing to replace an output directory with unrecognized files")
                destination.rename(Path(temp) / "previous")
            staged.rename(destination)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError):
            print(error.stderr.decode() if error.stderr else "", file=sys.stderr)
        sys.exit(1)
