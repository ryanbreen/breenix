//! Fixed drawing programs from the contract and TGSI's documented integer ISA.
use super::*;
use std::fmt::Write;

fn finalize(text: String, tokens: u32, registers: usize) -> (String, u32) {
    let mut tokens = tokens;
    let text = text.replace(
        &format!("DCL TEMP[0..{}]", registers - 1),
        &format!("DCL TEMP[0..{registers}]"),
    );
    let text = expand_sources(&text);
    let text = integer_words(&text, registers, &mut tokens);
    let (text, _) = integer_constants(&text, registers + 3, &mut tokens);
    tokens += text
        .lines()
        .filter(|l| {
            l.starts_with("UIF ") || matches!(*l, "BGNLOOP" | "ENDLOOP" | "BRK" | "ELSE" | "ENDIF")
        })
        .count() as u32;
    (text.trim_end_matches('\0').to_string(), tokens)
}

fn shape(pipe: u32) -> (String, u32) {
    let mut c = Code::default();
    let a: Vec<_> = (0..16).map(|i| c.input(i)).collect();
    let x = c.input(16);
    let y = c.input(17);
    let result = match pipe {
        10 => c.line(&[x, y, a[0], a[1], a[2], a[3]]),
        11 | 12 => c.circle(&[x, y, a[0], a[1], a[2]], pipe == 12),
        13 => c.rounded(&[x, y, a[0], a[1], a[2], a[3], a[4]]),
        _ => unreachable!(),
    };
    let (text, tokens, registers) = tgsi(&c, &[result]);
    // Replace only the common packed-word output epilogue. The model's one result
    // remains in its allocated scalar register, and the predicate stays on device.
    let marker = format!("MOV TEMP[{}].x,", registers - 3);
    let start = text.rfind(&marker).unwrap();
    let end = text[start..].find('\n').unwrap() + start + 1;
    let mut body = text[..end].replace("DCL CONST[0..4]", "DCL CONST[0..5]");
    writeln!(
        body,
        "UIF TEMP[{}].x\nMOV OUT[0], CONST[5]\nELSE\nKILL\nENDIF\nEND\n\0",
        registers - 3
    )
    .unwrap();
    // Removed byte extraction (32), U2F (3), MUL (4), END (1); added UIF,
    // colour MOV, ELSE/KILL/ENDIF/END. Optional label tokens counted by finalize.
    finalize(body, tokens - 40 + 2 + 3 + 1 + 1 + 1 + 1, registers)
}

pub fn generate(destination: &std::path::Path) {
    std::fs::create_dir_all(destination).unwrap();
    let mut module=String::from("// Generated by tools/gpu-profile/math.rs --pipelines.\nuse super::{pipe, Program};\npub const CATALOGUE: &[(u32, Program)] = &[\n");
    for pipe in 2..16 {
        let (text, tokens) = if pipe == 8 {
            spans()
        } else if pipe == 15 {
            triangle()
        } else if pipe == 14 {
            gradient()
        } else if pipe >= 10 {
            shape(pipe)
        } else {
            sampled(pipe)
        };
        std::fs::write(destination.join(format!("{pipe}.tgsi")), &text).unwrap();
        writeln!(module,"({pipe}, Program {{kind: pipe::SHADER_FRAGMENT, text: include_bytes!(\"{pipe}.tgsi\"), tokens: {tokens}}}),").unwrap();
        println!("pipeline={pipe} bytes={} tokens={tokens}", text.len());
    }
    module.push_str("];\n");
    std::fs::write(destination.join("mod.rs"), module).unwrap();
}

struct Asm {
    body: String,
    constants: Vec<u32>,
    guards: usize,
}
impl Asm {
    fn new() -> Self {
        Self {
            body: String::new(),
            constants: vec![0, 1, 2, 3],
            guards: 0,
        }
    }
    fn k(&mut self, v: u32) -> String {
        let i = self
            .constants
            .iter()
            .position(|&x| x == v)
            .unwrap_or_else(|| {
                self.constants.push(v);
                self.constants.len() - 1
            });
        format!("IMM[{}].{}", i / 4, ["x", "y", "z", "w"][i % 4])
    }
    fn emit(&mut self, s: impl AsRef<str>) {
        self.body.push_str(s.as_ref());
        self.body.push('\n');
    }
    fn op(&mut self, op: &str, d: &str, a: &str, b: &str) {
        self.emit(format!("{op} {d}, {a}, {b}"));
    }
    fn mov(&mut self, d: &str, a: &str) {
        self.emit(format!("MOV {d}, {a}"));
    }
    fn sub(&mut self, d: &str, a: &str, b: &str) {
        let ones = self.k(u32::MAX);
        let one = self.k(1);
        self.op("XOR", "TEMP[59]", b, &ones);
        self.op("UADD", "TEMP[59]", "TEMP[59]", &one);
        self.op("UADD", d, a, "TEMP[59]");
    }
    fn div(&mut self, d: &str, nlo: &str, nhi: &str, den: &str) {
        // 64 restoring steps; the top remainder carry is retained explicitly.
        let zero = self.k(0);
        let one = self.k(1);
        let bits = self.k(64);
        let b31 = self.k(31);
        self.mov("TEMP[50].x", nlo);
        self.mov("TEMP[50].y", nhi);
        self.mov("TEMP[51].x", &zero);
        self.mov("TEMP[51].y", &zero);
        self.mov("TEMP[52].x", &bits);
        self.emit("BGNLOOP");
        self.op("USHR", "TEMP[53].x", "TEMP[50].y", &b31);
        self.op("USHR", "TEMP[53].y", "TEMP[50].x", &b31);
        self.op("SHL", "TEMP[50].xy", "TEMP[50]", &one);
        self.op("OR", "TEMP[50].y", "TEMP[50].y", "TEMP[53].y");
        self.op("USHR", "TEMP[53].y", "TEMP[51].x", &b31);
        self.op("SHL", "TEMP[51].x", "TEMP[51].x", &one);
        self.op("OR", "TEMP[51].x", "TEMP[51].x", "TEMP[53].x");
        self.op("USLT", "TEMP[54].x", "TEMP[51].x", den);
        self.op("AND", "TEMP[54].x", "TEMP[54].x", &one);
        self.op("XOR", "TEMP[54].x", "TEMP[54].x", &one);
        self.op("OR", "TEMP[54].x", "TEMP[54].x", "TEMP[53].y");
        self.sub("TEMP[55].x", "TEMP[51].x", den);
        self.emit("UCMP TEMP[51].x, TEMP[54].x, TEMP[55].x, TEMP[51].x");
        self.op("SHL", "TEMP[51].y", "TEMP[51].y", &one);
        self.op("OR", "TEMP[51].y", "TEMP[51].y", "TEMP[54].x");
        let minus = self.k(u32::MAX);
        self.op("UADD", "TEMP[52].x", "TEMP[52].x", &minus);
        self.emit("UIF TEMP[52].x\nELSE\nBRK\nENDIF\nENDLOOP");
        self.mov(d, "TEMP[51].y");
    }
    /// Run `body` `n` times, in a loop whose bound is computed from `CONST[4].x`, which the
    /// encoder's catalogue and warm-up draws supply as 0 (`kernel/src/gpu/virgl/encode.rs`):
    /// the bound is not known when the program is compiled, so the program carries one
    /// copy of the body. This reduces the emitted arithmetic without relying on
    /// historical compile timings from uncommitted diagnostics. The 2 s watchdog
    /// bounds each fenced request, including any compilation it triggers.
    fn passes(&mut self, n: u32, body: impl FnOnce(&mut Self)) {
        let one = self.k(1);
        let count = self.k(n);
        self.op("UADD", "TEMP[57].x", "CONST[4].x", &count);
        self.mov("TEMP[57].y", "CONST[4].x");
        self.emit("BGNLOOP");
        body(self);
        self.op("UADD", "TEMP[57].y", "TEMP[57].y", &one);
        self.op("USLT", "TEMP[2].x", "TEMP[57].y", "TEMP[57].x");
        self.emit("UIF TEMP[2].x\nELSE\nBRK\nENDIF\nENDLOOP");
    }
    fn kill_zero(&mut self, condition: &str) {
        self.emit(format!("UIF {condition}"));
        self.guards += 1;
    }
    fn fetch(&mut self, d: &str, coord: &str, sampler: u32) {
        let f = self.k(255f32.to_bits());
        let half = self.k(0.5f32.to_bits());
        self.emit(format!("TXF {d}, {coord}, SAMP[{sampler}], 2D"));
        self.op("MUL", d, d, &f);
        self.op("ADD", d, d, &half);
        self.emit(format!("F2U {d}, {d}"));
    }
    fn unpack(&mut self, d: &str, word: &str) {
        for (c, shift) in [("x", 16), ("y", 8), ("z", 0), ("w", 24)] {
            let sh = self.k(shift);
            let ff = self.k(255);
            self.op("USHR", &format!("{d}.{c}"), word, &sh);
            self.op("AND", &format!("{d}.{c}"), &format!("{d}.{c}"), &ff);
        }
    }
    fn div255(&mut self, d: &str, a: &str) {
        let k128 = self.k(128);
        let k8 = self.k(8);
        self.op("UADD", d, a, &k128);
        self.op("USHR", "TEMP[58]", d, &k8);
        self.op("UADD", d, d, "TEMP[58]");
        self.op("USHR", d, d, &k8);
    }
    fn output(&mut self, a: &str) {
        let inv = self.k(0x3b808081);
        self.emit(format!("U2F TEMP[48], {a}"));
        self.op("MUL", "OUT[0]", "TEMP[48]", &inv);
        for _ in 0..self.guards {
            self.emit("ELSE\nKILL\nENDIF");
        }
        self.guards = 0;
        self.emit("END");
    }
    fn finish(self) -> (String, u32) {
        let maxreg = self
            .body
            .split("TEMP[")
            .skip(1)
            .filter_map(|s| s.split(']').next()?.parse::<usize>().ok())
            .max()
            .unwrap_or(61)
            .max(61)
            + 1;
        let mut text=String::from("FRAG\nDCL IN[0], POSITION, LINEAR\nDCL OUT[0], COLOR\nDCL CONST[0..7]\nDCL TEMP[0..61]\nDCL SAMP[0]\nDCL SAMP[1]\nDCL SAMP[2]\nDCL SVIEW[0], 2D, FLOAT\nDCL SVIEW[1], 2D, FLOAT\nDCL SVIEW[2], 2D, FLOAT\n");
        for (i, v) in self.constants.chunks(4).enumerate() {
            let mut k = [0; 4];
            k[..v.len()].copy_from_slice(v);
            writeln!(
                text,
                "IMM[{i}] UINT32 {{{}, {}, {}, {}}}",
                k[0], k[1], k[2], k[3]
            )
            .unwrap();
        }
        text = text.replace("DCL TEMP[0..61]", &format!("DCL TEMP[0..{maxreg}]"));
        text.push_str(&self.body);
        let mut tokens = 2 + 4 + 3 + 2 + 2 + 6 + 9 + self.constants.len().div_ceil(4) as u32 * 5;
        for l in self.body.lines() {
            let operands = l.matches(',').count() + usize::from(l.contains(' '));
            tokens += 1 + operands as u32;
        }
        // TXF's final texture target is an instruction texture token, not a register;
        // counting each comma-delimited field already includes that token.
        finalize(text, tokens, maxreg)
    }
}

fn sampled(pipe: u32) -> (String, u32) {
    let mut s = Asm::new();
    let z = s.k(0);
    let one = s.k(1);
    let ff = s.k(255);
    s.mov("TEMP[0]", &z);
    s.emit("F2I TEMP[0].xy, IN[0]");
    s.sub("TEMP[1].x", "TEMP[0].x", "CONST[0].x");
    s.sub("TEMP[1].y", "TEMP[0].y", "CONST[0].y");
    // The unsigned local coordinate check also rejects a negative difference.
    if matches!(pipe, 3 | 4 | 9) {
        let (w, h) = if pipe == 9 {
            ("CONST[1].x", "CONST[1].y")
        } else {
            ("CONST[0].z", "CONST[0].w")
        };
        if pipe == 9 {
            s.div("TEMP[1].x", "TEMP[1].x", &z, "CONST[1].z");
            s.div("TEMP[1].y", "TEMP[1].y", &z, "CONST[1].z");
        }
        s.op("USLT", "TEMP[2].x", "TEMP[1].x", w);
        s.op("USLT", "TEMP[2].y", "TEMP[1].y", h);
        s.op("AND", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
        s.kill_zero("TEMP[2].x");
    }
    if pipe == 2 {
        let sign = s.k(0x80000000);
        for axis in ["x", "y"] {
            let origin = format!("CONST[0].{axis}");
            let pixel = format!("TEMP[0].{axis}");
            let local = format!("TEMP[1].{axis}");
            s.op("USLT", "TEMP[17].x", &pixel, &origin);
            s.op("AND", "TEMP[17].y", &origin, &sign);
            s.op("USEQ", "TEMP[17].y", "TEMP[17].y", &z);
            s.op("AND", "TEMP[17].x", "TEMP[17].x", "TEMP[17].y");
            s.emit("UIF TEMP[17].x");
            s.sub(&local, &origin, &pixel);
            s.sub("TEMP[18].x", "CONST[1].x", &one);
            s.op("UADD", &local, &local, "TEMP[18].x");
            s.emit("ENDIF");
            s.div(&local, &local, &z, "CONST[1].x");
            s.emit("UIF TEMP[17].x");
            s.sub(&local, &z, &local);
            s.emit("ENDIF");
        }
    }
    if matches!(pipe, 3 | 4) {
        s.op("UMUL", "TEMP[2].x", "TEMP[1].x", "CONST[1].z");
        s.op("UMUL", "TEMP[2].y", "TEMP[1].y", "CONST[1].w");
        s.div("TEMP[3].x", "TEMP[2].x", &z, "CONST[0].z");
        s.div("TEMP[3].y", "TEMP[2].y", &z, "CONST[0].w");
        if pipe == 4 {
            s.op("UADD", "TEMP[2].x", "TEMP[1].x", &one);
            s.op("UADD", "TEMP[2].y", "TEMP[1].y", &one);
            s.op("UMUL", "TEMP[2].x", "TEMP[2].x", "CONST[1].z");
            s.op("UMUL", "TEMP[2].y", "TEMP[2].y", "CONST[1].w");
            s.div("TEMP[4].x", "TEMP[2].x", &z, "CONST[0].z");
            s.div("TEMP[4].y", "TEMP[2].y", &z, "CONST[0].w");
        }
        s.mov("TEMP[1].xy", "TEMP[3]");
        s.op("UADD", "TEMP[1].xy", "TEMP[1]", "CONST[1]");
    } else {
        s.op("UADD", "TEMP[1].x", "TEMP[1].x", "CONST[0].z");
        s.op("UADD", "TEMP[1].y", "TEMP[1].y", "CONST[0].w");
    }
    if pipe == 9 {
        s.emit("USEQ TEMP[2].x, CONST[1].w, IMM[0].xxxx\nUIF TEMP[2].x");
        s.mov("TEMP[1].x", "CONST[0].z");
        s.emit("ENDIF");
    }
    // Discard fragments whose fetch coordinate is outside the named texture.
    s.op("USLT", "TEMP[2].xy", "TEMP[1]", "CONST[6]");
    s.op("AND", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
    s.kill_zero("TEMP[2].x");
    s.mov("TEMP[1].zw", &z);
    if pipe == 4 {
        // Bin count, then the exact two-word sum for each channel.
        s.sub("TEMP[5].x", "TEMP[4].x", "TEMP[3].x");
        s.sub("TEMP[5].y", "TEMP[4].y", "TEMP[3].y");
        s.op("UMUL", "TEMP[5].x", "TEMP[5].x", "TEMP[5].y");
        s.mov("TEMP[11]", &z);
        s.mov("TEMP[12]", &z);
        s.mov("TEMP[6].xy", "TEMP[1]");
        s.op("UADD", "TEMP[4].xy", "TEMP[4]", "CONST[1]");
        // A bin must fit in the source before its first texel is fetched.
        s.op("USLT", "TEMP[2].xy", "CONST[6]", "TEMP[4]");
        s.op("OR", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
        s.op("USEQ", "TEMP[2].x", "TEMP[2].x", &z);
        s.kill_zero("TEMP[2].x");
        s.emit("BGNLOOP\nBGNLOOP");
        s.fetch("TEMP[10]", "TEMP[1]", 0);
        s.op("UADD", "TEMP[13]", "TEMP[11]", "TEMP[10]");
        s.op("USLT", "TEMP[14]", "TEMP[13]", "TEMP[11]");
        s.op("AND", "TEMP[14]", "TEMP[14]", &one);
        s.op("UADD", "TEMP[12]", "TEMP[12]", "TEMP[14]");
        s.mov("TEMP[11]", "TEMP[13]");
        s.op("UADD", "TEMP[1].x", "TEMP[1].x", &one);
        s.op("USLT", "TEMP[2].x", "TEMP[1].x", "TEMP[4].x");
        s.emit("UIF TEMP[2].x\nELSE\nBRK\nENDIF\nENDLOOP");
        s.mov("TEMP[1].x", "TEMP[6].x");
        s.op("UADD", "TEMP[1].y", "TEMP[1].y", &one);
        s.op("USLT", "TEMP[2].x", "TEMP[1].y", "TEMP[4].y");
        s.emit("UIF TEMP[2].x\nELSE\nBRK\nENDIF\nENDLOOP");
        let sh = s.k(1);
        s.op("USHR", "TEMP[5].y", "TEMP[5].x", &sh);
        s.op("UADD", "TEMP[13]", "TEMP[11]", "TEMP[5].yyyy");
        s.op("USLT", "TEMP[14]", "TEMP[13]", "TEMP[11]");
        s.op("AND", "TEMP[14]", "TEMP[14]", &one);
        s.op("UADD", "TEMP[12]", "TEMP[12]", "TEMP[14]");
        s.mov("TEMP[11]", "TEMP[13]");
        for c in ["x", "y", "z", "w"] {
            s.div(
                &format!("TEMP[10].{c}"),
                &format!("TEMP[11].{c}"),
                &format!("TEMP[12].{c}"),
                "TEMP[5].x",
            );
        }
        s.mov("TEMP[10].w", &ff);
    } else if pipe == 9 {
        // The bit-row source is one byte per row; coverage cells use their x coordinate.
        s.emit("USEQ TEMP[2].x, CONST[1].w, IMM[0].xxxx\nUIF TEMP[2].x");
        s.mov("TEMP[1].x", "CONST[0].z");
        s.fetch("TEMP[10]", "TEMP[1]", 0);
        s.sub("TEMP[2].x", "TEMP[0].x", "CONST[0].x");
        s.div("TEMP[2].x", "TEMP[2].x", &z, "CONST[1].z");
        // 5x7 table's left pixel is bit width-1.
        s.sub("TEMP[2].y", "CONST[1].x", &one);
        s.sub("TEMP[2].x", "TEMP[2].y", "TEMP[2].x");
        // A variable shift count is masked explicitly, as math.rs's emitters do.
        let k31 = s.k(31);
        s.op("AND", "TEMP[2].x", "TEMP[2].x", &k31);
        s.op("USHR", "TEMP[10].x", "TEMP[10].x", "TEMP[2].x");
        s.op("AND", "TEMP[10].x", "TEMP[10].x", &one);
        s.op("UMUL", "TEMP[10].x", "TEMP[10].x", &ff);
        s.emit("ELSE");
        s.fetch("TEMP[10]", "TEMP[1]", 0);
        s.emit("ENDIF");
    } else {
        s.fetch("TEMP[10]", "TEMP[1]", 0);
    }
    if matches!(pipe, 5 | 6 | 7 | 9) {
        s.mov("TEMP[0].zw", &z);
        s.fetch("TEMP[20]", "TEMP[0]", 1);
        if matches!(pipe, 7 | 9) {
            if pipe == 9 {
                s.mov("TEMP[10]", "TEMP[10].xxxx");
            } else {
                s.emit("UIF CONST[1].x\nELSE");
                s.mov("TEMP[10]", "TEMP[10].xxxx");
                s.emit("ENDIF");
            }
            s.unpack("TEMP[21]", "CONST[5].x");
            s.sub("TEMP[22]", &ff, "TEMP[10]");
            s.op("UMUL", "TEMP[23]", "TEMP[21]", "TEMP[10]");
            s.op("UMUL", "TEMP[24]", "TEMP[20]", "TEMP[22]");
            s.op("UADD", "TEMP[23]", "TEMP[23]", "TEMP[24]");
            s.div255("TEMP[10]", "TEMP[23]");
            s.mov("TEMP[10].w", &ff);
        } else {
            if pipe == 6 {
                s.op("UMUL", "TEMP[23].xyz", "TEMP[10]", "TEMP[10].wwww");
                s.div255("TEMP[23]", "TEMP[23]");
                s.mov("TEMP[10].xyz", "TEMP[23]");
            }
            s.sub("TEMP[22].x", &ff, "TEMP[10].w");
            s.op("UMUL", "TEMP[23]", "TEMP[20]", "TEMP[22].xxxx");
            s.div255("TEMP[23]", "TEMP[23]");
            s.op("UADD", "TEMP[10]", "TEMP[10]", "TEMP[23]");
        }
    }
    s.output("TEMP[10]");
    s.finish()
}

fn gradient() -> (String, u32) {
    let mut c = Code::default();
    let a: Vec<_> = (0..16).map(|i| c.input(i)).collect();
    let y = c.input(17);
    let i = c.sub(y, a[0]);
    let n = c.addk(a[1], u32::MAX);
    let zero = c.k(0);
    let one = c.k(1);
    let point = c.eq(n, zero);
    let den = c.sel(point, one, n);
    let rem = c.sub(n, i);
    let half = c.shrk(n, 1);
    let mut word = zero;
    for shift in [0, 8, 16, 24] {
        let top = c.shrk(a[3], shift);
        let top = c.andk(top, 255);
        let bottom = c.shrk(a[2], shift);
        let bottom = c.andk(bottom, 255);
        let ta = c.product(top, rem);
        let tb = c.product(bottom, i);
        let sum = c.addwide(&ta, &tb);
        let sum = c.addwide(&sum, &[half, zero]);
        let q = c.div96([sum[0], sum[1], zero], [den, zero, zero]);
        let v = c.sel(point, top, q[0]);
        let v = c.shlk(v, shift);
        word = c.or(word, v);
    }
    let (text, tokens, regs) = tgsi(&c, &[word]);
    finalize(
        text.replace("CONST[0].w", "CONST[5].x")
            .replace("DCL CONST[0..4]", "DCL CONST[0..7]"),
        tokens,
        regs,
    )
}

impl Asm {
    fn block(&mut self, c: Code, result: V, inputs: &[&str], destination: &str) {
        let (text, _, regs) = tgsi(&c, &[result]);
        let mut immediates = Vec::new();
        for l in text.lines().filter(|l| l.starts_with("IMM[")) {
            let begin = l.find('{').unwrap();
            let end = l.find('}').unwrap();
            let values: Vec<u32> = l[begin + 1..end]
                .split(", ")
                .map(|w| w.parse().unwrap())
                .collect();
            for v in values {
                immediates.push(self.k(v));
            }
        }
        let marker = format!("MOV TEMP[{}].x,", regs - 3);
        let end = text.rfind(&marker).unwrap();
        let end = end + text[end..].find('\n').unwrap() + 1;
        for l in text[..end].lines().skip_while(|l| !l.starts_with("F2I")) {
            if l.starts_with("F2I") {
                continue;
            }
            let mut l = l.to_string();
            for (i, input) in inputs.iter().enumerate() {
                let _ = input;
                l = l.replace(
                    &format!("CONST[{}].{}", i / 4, ["x", "y", "z", "w"][i % 4]),
                    &format!("ARG[{i}]"),
                );
            }
            // Helpers' temporary names occupy a separate register range.
            for i in (0..regs).rev() {
                l = l.replace(&format!("TEMP[{i}]"), &format!("HELP[{}]", 100 + i));
            }
            l = l.replace("HELP[", "TEMP[");
            for (i, input) in inputs.iter().enumerate() {
                l = l.replace(&format!("ARG[{i}]"), input);
            }
            for i in (0..immediates.len()).rev() {
                l = l.replace(
                    &format!("IMM[{}].{}", i / 4, ["x", "y", "z", "w"][i % 4]),
                    &format!("LIT[{i}]"),
                );
            }
            for (i, k) in immediates.iter().enumerate() {
                l = l.replace(&format!("LIT[{i}]"), k);
            }
            self.emit(l);
        }
        self.mov(destination, &format!("TEMP[{}].x", 100 + regs - 3));
    }
    fn data_word(&mut self, d: &str, index: &str) {
        let z = self.k(0);
        let one = self.k(1);
        self.op("SHL", "TEMP[43].x", &one, "CONST[6].w");
        self.sub("TEMP[43].x", "TEMP[43].x", &one);
        self.op("UADD", "TEMP[43].y", index, "CONST[6].z");
        self.mov("TEMP[40]", &z);
        self.op("AND", "TEMP[40].x", "TEMP[43].y", "TEMP[43].x");
        self.op("USHR", "TEMP[40].y", "TEMP[43].y", "CONST[6].w");
        self.fetch("TEMP[41]", "TEMP[40]", 2);
        self.mov(d, "TEMP[41].x");
        for (component, bits) in [("y", 8), ("z", 16), ("w", 24)] {
            let sh = self.k(bits);
            self.op("SHL", "TEMP[42].x", &format!("TEMP[41].{component}"), &sh);
            self.op("OR", d, d, "TEMP[42].x");
        }
    }
}

/// `triangle`: the model's area test, then its edge test run three times (`Asm::passes`),
/// the vertices rotating between passes. Both are `Code::triangle`'s own helpers, so the
/// program computes the predicate the probe's routine 23 does; it is about half the
/// length of one with three edge copies, which on Parallels compiled for 0.43 to 0.75 s.
fn triangle() -> (String, u32) {
    let mut s = Asm::new();
    let z = s.k(0);
    let one = s.k(1);
    s.mov("TEMP[0]", &z);
    s.emit("F2I TEMP[0].xy, IN[0]");
    // Nonzero area in bit 0 and negative area in bit 1.
    let mut c = Code::default();
    let v: Vec<_> = (0..6).map(|i| c.input(i)).collect();
    let w: Vec<_> = v.iter().map(|&a| c.wide(a)).collect();
    let (valid, negative) = c.triangle_area(&w[0], &w[1], &w[2], &w[3], &w[4], &w[5]);
    let negative = c.shlk(negative, 1);
    let packed = c.or(valid, negative);
    s.block(c, packed, &["CONST[0].x", "CONST[0].y", "CONST[0].z", "CONST[0].w", "CONST[1].x", "CONST[1].y"], "TEMP[20].x");
    s.op("AND", "TEMP[20].y", "TEMP[20].x", &one);
    s.op("USHR", "TEMP[20].z", "TEMP[20].x", &one);
    // Edge a to b, then the vertices after it: (v0, v1), (v1, v2), (v2, v0).
    for (d, from) in [("TEMP[21].x", "CONST[0].x"), ("TEMP[21].y", "CONST[0].y"), ("TEMP[21].z", "CONST[0].z"),
        ("TEMP[21].w", "CONST[0].w"), ("TEMP[22].x", "CONST[1].x"), ("TEMP[22].y", "CONST[1].y"),
        ("TEMP[22].z", "CONST[0].x"), ("TEMP[22].w", "CONST[0].y")] {
        s.mov(d, from);
    }
    s.passes(3, |s| {
        let mut c = Code::default();
        let a: Vec<_> = (0..7).map(|i| c.input(i)).collect();
        let (px, py) = c.centre(a[0], a[1]);
        let w: Vec<_> = a[2..6].iter().map(|&v| c.wide(v)).collect();
        let accept = c.triangle_edge(&px, &py, &w[0], &w[1], &w[2], &w[3], a[6]);
        s.block(c, accept, &["TEMP[0].x", "TEMP[0].y", "TEMP[21].x", "TEMP[21].y", "TEMP[21].z", "TEMP[21].w", "TEMP[20].z"], "TEMP[23].x");
        s.op("AND", "TEMP[20].y", "TEMP[20].y", "TEMP[23].x");
        for (d, from) in [("TEMP[21].x", "TEMP[21].z"), ("TEMP[21].y", "TEMP[21].w"), ("TEMP[21].z", "TEMP[22].x"),
            ("TEMP[21].w", "TEMP[22].y"), ("TEMP[22].x", "TEMP[22].z"), ("TEMP[22].y", "TEMP[22].w")] {
            s.mov(d, from);
        }
    });
    s.emit("UIF TEMP[20].y\nMOV OUT[0], CONST[5]\nELSE\nKILL\nENDIF\nEND");
    s.finish()
}

fn spans() -> (String, u32) {
    let mut s = Asm::new();
    let z = s.k(0);
    let one = s.k(1);
    let eight = s.k(8);
    let two = s.k(2);
    let fone = s.k(1f32.to_bits());
    let sign = s.k(0x80000000);
    s.mov("TEMP[0]", &z);
    s.emit("F2I TEMP[0].xy, IN[0]");
    s.sub("TEMP[1].x", "TEMP[0].x", "CONST[0].x");
    s.sub("TEMP[1].y", "TEMP[0].y", "CONST[0].y");
    s.op("USLT", "TEMP[2].xy", "TEMP[1]", "CONST[0].zwzw");
    s.op("AND", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
    s.kill_zero("TEMP[2].x");
    s.emit("U2F TEMP[3].x, TEMP[1].xxxx\nU2F TEMP[3].y, CONST[0].zzzz");
    let shift = s.k(2);
    s.op("USHR", "TEMP[4].x", "CONST[1].x", &shift);
    s.op("UMUL", "TEMP[4].y", "CONST[0].w", &eight);
    s.op("UADD", "TEMP[4].y", "TEMP[4].y", &one);
    s.op("UADD", "TEMP[4].y", "TEMP[4].y", "TEMP[4].x");
    s.mov("TEMP[5].x", &z);
    s.mov("TEMP[6].x", &z);
    s.emit("BGNLOOP");
    s.op("UMUL", "TEMP[7].x", "TEMP[1].y", &eight);
    s.op("UADD", "TEMP[7].x", "TEMP[7].x", "TEMP[5].x");
    s.op("UADD", "TEMP[7].x", "TEMP[7].x", "TEMP[4].x");
    s.data_word("TEMP[8].x", "TEMP[7].x");
    s.op("UADD", "TEMP[7].x", "TEMP[7].x", &one);
    s.data_word("TEMP[8].y", "TEMP[7].x");
    s.mov("TEMP[9].xy", &z); // winding, fill_start
    s.emit("BGNLOOP");
    s.op("USLT", "TEMP[2].x", "TEMP[8].x", "TEMP[8].y");
    s.emit("UIF TEMP[2].x");
    s.op("UMUL", "TEMP[7].x", "TEMP[8].x", &two);
    s.op("UADD", "TEMP[7].x", "TEMP[7].x", "TEMP[4].y");
    s.data_word("TEMP[10].x", "TEMP[7].x");
    s.op("UADD", "TEMP[7].x", "TEMP[7].x", &one);
    s.data_word("TEMP[10].y", "TEMP[7].x");
    s.emit("ELSE");
    s.mov("TEMP[10].x", "TEMP[3].y");
    s.sub("TEMP[10].y", &z, "TEMP[9].x");
    s.emit("ENDIF");
    s.mov("TEMP[11].x", "TEMP[9].x");
    s.op("UADD", "TEMP[9].x", "TEMP[9].x", "TEMP[10].y");
    s.op("USEQ", "TEMP[2].x", "TEMP[11].x", &z);
    s.emit("UIF TEMP[2].x");
    s.mov("TEMP[9].y", "TEMP[10].x");
    s.emit("ELSE");
    s.op("USEQ", "TEMP[2].x", "TEMP[9].x", &z);
    s.emit("UIF TEMP[2].x");
    // Clamp finite span endpoints to [0,width] using sign and positive bit order.
    s.op("AND", "TEMP[2].x", "TEMP[9].y", &sign);
    s.emit("UCMP TEMP[12].x, TEMP[2].x, IMM[0].xxxx, TEMP[9].y");
    s.op("AND", "TEMP[2].x", "TEMP[10].x", &sign);
    s.emit("UCMP TEMP[12].y, TEMP[2].x, IMM[0].xxxx, TEMP[10].x");
    s.op("USLT", "TEMP[2].x", "TEMP[3].y", "TEMP[12].y");
    s.emit("UCMP TEMP[12].y, TEMP[2].x, TEMP[3].y, TEMP[12].y");
    s.op("USLT", "TEMP[2].x", "TEMP[12].x", "TEMP[12].y");
    s.emit("UIF TEMP[2].x");
    // Exact positive binary32 truncation and ceil implemented with integer words.
    let mut c = Code::default();
    let a = c.input(0);
    let out = c.float_trunc(a);
    s.block(c, out, &["TEMP[12].x"], "TEMP[13].x");
    let mut c = Code::default();
    let a = c.input(0);
    let out = c.float_ceil(a);
    let out = c.float_trunc(out);
    s.block(c, out, &["TEMP[12].y"], "TEMP[13].y");
    s.op("USLT", "TEMP[2].x", "CONST[0].z", "TEMP[13].y");
    s.emit("UCMP TEMP[13].y, TEMP[2].x, CONST[0].z, TEMP[13].y");
    s.op("USLT", "TEMP[2].x", "TEMP[13].x", "TEMP[13].y");
    s.op("USLT", "TEMP[2].y", "TEMP[1].x", "TEMP[13].x");
    s.op("USEQ", "TEMP[2].y", "TEMP[2].y", &z);
    s.op("AND", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
    s.op("USLT", "TEMP[2].y", "TEMP[1].x", "TEMP[13].y");
    s.op("AND", "TEMP[2].x", "TEMP[2].x", "TEMP[2].y");
    s.emit("UIF TEMP[2].x");
    s.op("UADD", "TEMP[14].x", "TEMP[13].x", &one);
    s.op("USEQ", "TEMP[2].x", "TEMP[14].x", "TEMP[13].y");
    s.emit("UIF TEMP[2].x");
    s.mov("TEMP[15].x", "TEMP[12].y");
    s.mov("TEMP[15].y", "TEMP[12].x");
    s.emit("ELSE");
    s.op("USEQ", "TEMP[2].x", "TEMP[1].x", "TEMP[13].x");
    s.emit("UIF TEMP[2].x\nU2F TEMP[15].x, TEMP[14].xxxx");
    s.mov("TEMP[15].y", "TEMP[12].x");
    s.emit("ELSE");
    s.sub("TEMP[14].x", "TEMP[13].y", &one);
    s.op("USEQ", "TEMP[2].x", "TEMP[1].x", "TEMP[14].x");
    s.emit("UIF TEMP[2].x");
    s.mov("TEMP[15].x", "TEMP[12].y");
    s.emit("U2F TEMP[15].y, TEMP[14].xxxx\nELSE");
    s.mov("TEMP[15].x", &fone);
    s.mov("TEMP[15].y", &z);
    s.emit("ENDIF\nENDIF\nENDIF");
    // The span's length, then the running sum: one binary32 addition, run twice.
    s.op("XOR", "TEMP[16].y", "TEMP[15].y", &sign);
    s.mov("TEMP[16].x", "TEMP[15].x");
    s.passes(2, |s| {
        let mut c = Code::default();
        let a = c.input(0);
        let b = c.input(1);
        let out = c.float_add(a, b);
        s.block(c, out, &["TEMP[16].x", "TEMP[16].y"], "TEMP[16].z");
        s.mov("TEMP[16].x", "TEMP[6].x");
        s.mov("TEMP[16].y", "TEMP[16].z");
    });
    s.mov("TEMP[6].x", "TEMP[16].z");
    s.emit("ENDIF\nENDIF\nENDIF\nENDIF");
    s.op("USEQ", "TEMP[2].x", "TEMP[8].x", "TEMP[8].y");
    s.emit("UIF TEMP[2].x\nBRK\nENDIF");
    s.op("UADD", "TEMP[8].x", "TEMP[8].x", &one);
    s.emit("ENDLOOP");
    s.op("UADD", "TEMP[5].x", "TEMP[5].x", &one);
    s.op("USLT", "TEMP[2].x", "TEMP[5].x", &eight);
    s.emit("UIF TEMP[2].x\nELSE\nBRK\nENDIF\nENDLOOP");
    // The sum times 1/8, then times 255: one binary32 multiplication, run twice.
    let eighth = s.k(0.125f32.to_bits());
    let scale = s.k(255f32.to_bits());
    s.mov("TEMP[16].x", "TEMP[6].x");
    s.mov("TEMP[16].y", &eighth);
    s.passes(2, |s| {
        let mut c = Code::default();
        let a = c.input(0);
        let b = c.input(1);
        let out = c.float_mul(a, b);
        s.block(c, out, &["TEMP[16].x", "TEMP[16].y"], "TEMP[16].x");
        s.mov("TEMP[16].y", &scale);
    });
    let mut c = Code::default();
    let a = c.input(0);
    let v = c.float_trunc(a);
    let ff = c.k(255);
    let hi = c.lt(ff, v);
    let v = c.sel(hi, ff, v);
    s.block(c, v, &["TEMP[16].x"], "TEMP[10].x");
    s.mov("TEMP[10]", "TEMP[10].xxxx");
    s.mov("TEMP[0].zw", &z);
    s.fetch("TEMP[20]", "TEMP[0]", 1);
    s.unpack("TEMP[21]", "CONST[5].x");
    let ff = s.k(255);
    s.sub("TEMP[22]", &ff, "TEMP[10]");
    s.op("UMUL", "TEMP[23]", "TEMP[21]", "TEMP[10]");
    s.op("UMUL", "TEMP[24]", "TEMP[20]", "TEMP[22]");
    s.op("UADD", "TEMP[23]", "TEMP[23]", "TEMP[24]");
    s.div255("TEMP[10]", "TEMP[23]");
    s.mov("TEMP[10].w", &ff);
    s.output("TEMP[10]");
    s.finish()
}
