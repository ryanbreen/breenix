#!/bin/bash
# Build the libc suite's C programs against Breenix's own C library.
#
#   userspace/libc-suite/build.sh --arch aarch64|x86_64
#
# For each category listed in userspace/libc-suite/categories, compiles harness.c and
# <category>.c (with '-' in the id as '_') with scripts/breenix-cc and links
# userspace/programs/{,aarch64/}libc-<category>_test.elf, which the disk installs in
# /usr/libexec/breenix. abi_check.c is compiled for the arch during this build.
#
# A function the category's code calls that libc.a does not define yet gets a stand-in
# in build/<arch>/missing-<category>.c that calls libc_case_missing("<name>"), so each
# case reaching it fails by name. Data objects cannot be stood in for: a missing one
# fails the build. A category marked `complete` in the categories file gets no
# stand-ins, so any undefined symbol fails its build.
#
# Needs libc.a for the arch (libs/libbreenix-libc, built by userspace/programs/build.sh).
set -euo pipefail
export LC_ALL=C

SUITE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SUITE/../.." && pwd)"

ARCH=""
while [ $# -gt 0 ]; do
    case "$1" in
        --arch) ARCH="$2"; shift 2 ;;
        *) echo "usage: $0 --arch aarch64|x86_64" >&2; exit 2 ;;
    esac
done
case "$ARCH" in
    aarch64)
        OUT="$ROOT/userspace/programs/aarch64"
        LIBC="$ROOT/libs/libbreenix-libc/target/aarch64-breenix/release/libc.a"
        ;;
    x86_64)
        OUT="$ROOT/userspace/programs"
        LIBC="$ROOT/libs/libbreenix-libc/target/x86_64-breenix-c/release/libc.a"
        ;;
    *) echo "usage: $0 --arch aarch64|x86_64" >&2; exit 2 ;;
esac

CC=("$ROOT/scripts/breenix-cc" --arch "$ARCH")
CFLAGS=(-std=c17 -fno-builtin -frounding-math -O2 -Wall -Werror -I "$SUITE")
NM="$("$ROOT/scripts/breenix-cc" --arch "$ARCH" --tool-dir)/llvm-nm"
[ -x "$NM" ] || NM="$(command -v llvm-nm || true)"
[ -x "$NM" ] || { echo "libc-suite: llvm-nm not found next to clang or on PATH" >&2; exit 1; }
[ -f "$LIBC" ] || { echo "libc-suite: $LIBC is missing" >&2; exit 1; }

# Objects every program could take from the library: data must be defined, functions
# may be stood in for.
DATA_SYMBOLS=" stdin stdout stderr optind optarg opterr optopt signgam environ timezone daylight tzname "

BUILD="$SUITE/build/$ARCH"
rm -rf "$BUILD"
mkdir -p "$BUILD" "$OUT"

"${CC[@]}" "${CFLAGS[@]}" -c "$SUITE/abi_check.c" -o "$BUILD/abi_check.o"
"${CC[@]}" "${CFLAGS[@]}" -c "$SUITE/harness.c" -o "$BUILD/harness.o"

# Every symbol libc.a defines, strongly or weakly.
"$NM" --defined-only --format=just-symbols "$LIBC" 2>/dev/null | sort -u > "$BUILD/libc-defined.txt"

listed=" "
while read -r category mode extra; do
    case "$category" in ''|'#'*) continue ;; esac
    if [ -n "$extra" ] || { [ -n "$mode" ] && [ "$mode" != complete ]; }; then
        echo "libc-suite: bad line in categories: $category $mode $extra" >&2
        exit 1
    fi
    source_file="$SUITE/${category//-/_}.c"
    [ -f "$source_file" ] || { echo "libc-suite: no $source_file for category $category" >&2; exit 1; }
    listed+="$category "
    object="$BUILD/$category.o"
    "${CC[@]}" "${CFLAGS[@]}" -c "$source_file" -o "$object"

    # Undefined in the program's own objects and not defined there or in libc.a.
    "$NM" --defined-only --format=just-symbols "$object" "$BUILD/harness.o" | sort -u > "$BUILD/$category-defined.txt"
    "$NM" --undefined-only --format=just-symbols "$object" "$BUILD/harness.o" | sort -u \
        | comm -23 - "$BUILD/$category-defined.txt" | comm -23 - "$BUILD/libc-defined.txt" > "$BUILD/$category-missing.txt"

    missing_data=""
    missing_functions=()
    while read -r symbol; do
        [ -n "$symbol" ] || continue
        if [[ "$DATA_SYMBOLS" == *" $symbol "* ]]; then
            missing_data+=" $symbol"
        else
            missing_functions+=("$symbol")
        fi
    done < "$BUILD/$category-missing.txt"
    if [ -n "$missing_data" ]; then
        echo "libc-suite: $category uses data Breenix's C library does not define:$missing_data" >&2
        exit 1
    fi
    objects=("$object" "$BUILD/harness.o")
    if [ "${#missing_functions[@]}" -gt 0 ]; then
        if [ "$mode" = complete ]; then
            echo "libc-suite: $category is complete but libc.a lacks: ${missing_functions[*]}" >&2
            exit 1
        fi
        shims="$BUILD/missing-$category.c"
        {
            echo "/* Generated by userspace/libc-suite/build.sh: functions libc.a does not define yet. */"
            echo "void libc_case_missing(const char *name);"
            for symbol in "${missing_functions[@]}"; do
                echo "void $symbol(void) { libc_case_missing(\"$symbol\"); }"
            done
        } > "$shims"
        "${CC[@]}" -std=c17 -O2 -fno-builtin -w -c "$shims" -o "$BUILD/missing-$category.o"
        objects+=("$BUILD/missing-$category.o")
        echo "  libc-$category: ${#missing_functions[@]} functions not in libc yet: ${missing_functions[*]}"
    else
        echo "  libc-$category: every function it uses is in libc"
    fi
    "${CC[@]}" "${objects[@]}" -o "$OUT/libc-${category}_test.elf"
done < "$SUITE/categories"

# A category taken out of the list must not leave its old program installed.
for elf in "$OUT"/libc-*_test.elf; do
    [ -e "$elf" ] || continue
    name="$(basename "$elf" _test.elf)"
    name="${name#libc-}"
    if [[ "$listed" != *" $name "* ]]; then
        rm -f "$elf"
    fi
done
