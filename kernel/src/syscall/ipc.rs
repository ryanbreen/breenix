//! Linux IPC syscall numbers; lane dispatchers recognize implemented calls only.

use super::SyscallResult;

pub use super::{
    MQ_GETSETATTR_SYSCALL_NUMBER, MQ_NOTIFY_SYSCALL_NUMBER, MQ_OPEN_SYSCALL_NUMBER,
    MQ_TIMEDRECEIVE_SYSCALL_NUMBER, MQ_TIMEDSEND_SYSCALL_NUMBER, MQ_UNLINK_SYSCALL_NUMBER,
    MSGCTL_SYSCALL_NUMBER, MSGGET_SYSCALL_NUMBER, MSGRCV_SYSCALL_NUMBER, MSGSND_SYSCALL_NUMBER,
    SEMCTL_SYSCALL_NUMBER, SEMGET_SYSCALL_NUMBER, SEMOP_SYSCALL_NUMBER, SEMTIMEDOP_SYSCALL_NUMBER,
    SHMAT_SYSCALL_NUMBER, SHMCTL_SYSCALL_NUMBER, SHMDT_SYSCALL_NUMBER, SHMGET_SYSCALL_NUMBER,
};

pub fn dispatch(n: u64, a: [u64; 6]) -> Option<SyscallResult> {
    super::mqueue::dispatch(n, a).or_else(|| super::sysv::dispatch(n, a))
}
