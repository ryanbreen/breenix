//! One boot-CPU native preferred-mode takeover, before console rendering starts.
//! Hardware mechanisms adapted from the checked MIT sources in THIRD_PARTY_NOTICES.
use super::{board, edid, memory, modeset, Registers};
use crate::{arch_impl::x86_64::timer, drivers::pci};
use alloc::{format, string::String, vec::Vec};
use core::fmt::Write;
use modeset::Io;
impl Io for Registers {
    fn read(&mut self, r: usize) -> u32 {
        Registers::read(self, r)
    }
    fn write(&mut self, r: usize, v: u32) {
        Registers::write(self, r, v);
    }
    fn delay_us(&mut self, us: u32) {
        let ticks = timer::frequency_hz() / 1_000_000 * u64::from(us);
        let begin = timer::rdtsc();
        while timer::rdtsc().wrapping_sub(begin) < ticks {
            core::hint::spin_loop();
        }
    }
}
fn write_words(
    regs: &mut Registers,
    total: u64,
    start: u64,
    words: &[u32],
) -> Result<(), &'static str> {
    let mut p = memory::Pramin::new(regs, total);
    for (i, v) in words.iter().enumerate() {
        p.write(start + i as u64 * 4, *v)?;
    }
    Ok(())
}
fn read_word(regs: &mut Registers, total: u64, address: u64) -> Result<u32, &'static str> {
    memory::Pramin::new(regs, total).read(address)
}
fn submit(
    regs: &mut Registers,
    total: u64,
    push: u64,
    put: &mut u32,
    methods: &[(u32, u32)],
) -> Result<(), &'static str> {
    if *put as usize + methods.len() * 8 > 2048 {
        return Err("native core push storage exhausted");
    }
    let mut words = Vec::new();
    for (method, value) in methods {
        words.extend([0x00040000 | method, *value]);
    }
    write_words(regs, total, push + u64::from(*put), &words)?;
    *put += words.len() as u32 * 4;
    modeset::publish(regs, *put)
}
fn complete(
    regs: &mut Registers,
    total: u64,
    notifier: u64,
    limits: &modeset::PllLimits,
    coefficients: &modeset::Pll,
    route: (u32, u32),
    scripts: &[Vec<modeset::Op>; 4],
) -> Result<u32, &'static str> {
    let (head, sor) = route;
    let h = head as usize * 0x800;
    for _ in 0..2000 {
        let errors = regs.read(0x61009c);
        if errors != 0 {
            return Err("native display method error");
        }
        let pending = regs.read(0x6100ac) & 7;
        if pending != 0 {
            let phase = if pending & 1 != 0 {
                1
            } else if pending & 2 != 0 {
                2
            } else {
                4
            };
            let state = regs.read(0x6101d4 + h);
            regs.write(0x6100ac, phase);
            if state & 0x1000 != 0 {
                if phase == 1 {
                    modeset::execute_ops(regs, &scripts[0]);
                }
                if phase == 2 {
                    modeset::execute_ops(regs, &scripts[1]);
                }
                if phase == 4 {
                    modeset::execute_ops(regs, &scripts[3]);
                }
            }
            if phase == 2 && state & 0x10000 != 0 {
                let r = limits.reg as usize;
                regs.mask(r + 12, 0, 0x100);
                regs.write(
                    r + 4,
                    coefficients.p << 16 | coefficients.n << 8 | coefficients.m,
                );
                regs.write(r + 16, u32::from(coefficients.fraction) << 16);
            }
            if phase == 2 && state & 0x1000 != 0 {
                modeset::execute_ops(regs, &scripts[2]);
                regs.mask(0x612200 + h, 15, 0);
                let s = sor as usize * 0x800;
                regs.mask(0x612300 + s, 0x007c0707, 0x0a << 18);
                modeset::wait(regs, 0x61c004 + s, 0x80000000, 0)?;
                regs.mask(0x61c004 + s, 0x80000001, 0x80000001);
                modeset::wait(regs, 0x61c004 + s, 0x80000000, 0)?;
                modeset::wait(regs, 0x61c030 + s, 0x10000000, 0)?;
            }
            for i in 0..4 {
                regs.write(0x6101d4 + i * 0x800, 0);
            }
            regs.write(0x6101d0, 0x80000000);
        }
        let value = read_word(regs, total, notifier)?;
        if value & 1 != 0 {
            return Ok(value);
        }
        regs.delay_us(1000);
    }
    Err("native update notifier did not complete")
}
pub struct ConsoleSurface {
    pub pointer: usize,
    pub bytes: usize,
    pub width: usize,
    pub height: usize,
    pub pitch: usize,
    pub vram: u64,
    pub regs: usize,
    pub head: u32,
    pub phys: u64,
    pub firmware_baseline: u64,
}

pub fn takeover(
    regs: &mut Registers,
    device: pci::Device,
    rom: &[u8],
    t: &edid::Timing,
    route: &board::Route,
    head: u32,
    layout: &memory::Layout,
) -> Result<ConsoleSurface, &'static str> {
    let limits = modeset::board_pll(rom, head)?;
    let pll_record = modeset::board_pll_record(rom,head)?;
    let coefficients = modeset::pll(&limits, t.clock_khz)?;
    let protocol = if route.conf & 0x10 != 0 {
        1
    } else if route.conf & 0x20 != 0 {
        2
    } else {
        return Err("no TMDS link");
    };
    let scripts = modeset::board_scripts(rom, head, u32::from(route.sor), protocol, t.clock_khz)
        .map_err(|e| {
            let end = e.offset.saturating_add(256).min(rom.len());
            let excerpt = rom.get(e.offset..end).unwrap_or(&[]);
            crate::serial_println!(
                "GT710_SCRIPT_REFUSAL offset={} opcode={:#x} reason={} bytes={}",
                e.offset,
                e.opcode,
                e.reason,
                super::hex(excerpt)
            );
            e.reason
        })?;
    let surface = layout.objects[0].range;
    let evo = layout.objects[2].range.start;
    let notifier = layout.objects[3].range.start;
    let instance = layout.objects[4].range.start;
    let total = memory::discover(regs, device.bars[1].size)?.total;
    let page = if regs.read(0x100c80) & 1 != 0 { 16 } else { 17 };
    let (base,displacement,pages)=modeset::bar1_view(surface.start,surface.size,device.bars[1].size,page)?;
    let methods = modeset::head_methods(
        t,
        head,
        u32::from(route.sor),
        protocol,
        surface.start,
        layout.pitch,
    )?;
    crate::serial_println!(
        "GT710_MODE_STAGE preflight head={} sor={} clock={} pll={:#x} script-ops={:?}",
        head,
        route.sor,
        t.clock_khz,
        limits.reg,
        scripts.each_ref().map(|s| s.len())
    );
    // Prepare CPU aliases before changing the BAR GPU translation.
    let pointer = crate::memory::map_mmio(device.bars[1].address, modeset::BAR1_WINDOW)? + displacement;
    crate::console::display::linear::map_native_write_combining(
        device.bars[1].address,
        device.bars[1].size,
    )?;
    let firmware_baseline = crate::firmware_writes::count();
    regs.write(0x610090, 0);
    regs.write(0x6100a0, 0);
    // Supervisor requests remain enabled while the boot CPU polls their status.
    regs.write(0x6100b0, 0x307);
    if regs.read(0x6100ac) & 0x100 != 0 {
        regs.write(0x6100ac, 0x100);
        regs.mask(0x6194e8, 1, 0);
        modeset::wait(regs, 0x6194e8, 2, 0)?;
    }
    for i in 0..4 {
        for n in 0..3 {
            let v = regs.read(0x616104 + i * 0x800 + n * 4);
            regs.write(0x6101b4 + i * 0x800 + n * 4, v);
        }
        let v = regs.read(0x61c000 + i * 0x800);
        regs.write(0x6301c4 + i * 0x800, v);
    }
    // Apply the GF119 engine setup before tearing down inherited channels.
    regs.mask(0x616308 + head as usize * 0x800, 0x111, 0x10);
    modeset::stop_requests(regs)?;
    let quiesce_before:[u32;17]=core::array::from_fn(|i|regs.read(0x610490+i*16));
    crate::serial_println!("GT710_MODE_STAGE requests-disabled core={:#x} instance={:#x}",
        quiesce_before[0],regs.read(0x610010));
    // Owned storage only; inherited instance and command bytes remain untouched.
    {
        let mut p = memory::Pramin::new(regs, total);
        for object in &layout.objects[2..] {
            for a in (object.range.start..object.range.end().unwrap()).step_by(4) {
                p.write(a, 0)?;
            }
        }
    }
    let iso = modeset::dma_object(0, total)?;
    let notify = modeset::dma_object(notifier, 4096)?;
    write_words(regs, total, instance + 0x1000, &iso)?;
    write_words(regs, total, instance + 0x1020, &notify)?;
    write_words(
        regs,
        total,
        instance + modeset::ramht_slot(1, 0),
        &[1, (0x1000 << 9) | 1],
    )?;
    write_words(
        regs,
        total,
        instance + modeset::ramht_slot(2, 0),
        &[2, (0x1020 << 9) | 1],
    )?;
    modeset::bar_flush(regs)?;
    regs.write(0x610010, (instance >> 8) as u32 | 9);
    modeset::prepare_disabled_core(regs,evo)?;
    modeset::initialize_empty_core(regs,instance,evo)?;
    crate::serial_println!("GT710_MODE_STAGE empty-core-ready control={:#x} put={} get={}",
        regs.read(0x610490),regs.read(0x640000),regs.read(0x640004));
    modeset::quiesce(regs).inspect_err(|_| {
        for channel in 0..17 {
            crate::serial_println!("GT710_QUIESCE channel={} control={:#x} push={:#x}",
                channel,regs.read(0x610490+channel*16),regs.read(0x610494+channel*16));
        }
        crate::serial_println!("GT710_QUIESCE bios={:#x} underflow={:#x} tsc_hz={} instance={:#x}",
            regs.read(0x6194e8),regs.read(0x616308+head as usize*0x800),timer::frequency_hz(),regs.read(0x610010));
    })?;
    let quiesce_after:[u32;17]=core::array::from_fn(|i|regs.read(0x610490+i*16));
    regs.mask(0x610490, 16, 16);
    regs.write(0x640000, 0);
    regs.write(0x610490, 0x01000013);
    modeset::wait(regs, 0x610490, 0x80000000, 0)?;
    crate::serial_println!(
        "GT710_MODE_STAGE native-core control={:#x} instance={:#x}",
        regs.read(0x610490),
        regs.read(0x610010)
    );
    let seed = (timer::rdtsc() as u32) | 1;
    {
        let mut p = memory::Pramin::new(regs, total);
        for y in 0..t.height {
            for x in 0..layout.pitch / 4 {
                let v = 0xff000000
                    | (seed
                        .wrapping_add(y * 257)
                        .wrapping_add((x as u32 / 64) * 0x10203)
                        & 0xffffff);
                p.write(surface.start + u64::from(y) * layout.pitch + x * 4, v)?;
            }
        }
    }
    // Enable sticky reporting in repeat mode for the native measurement window.
    regs.mask(0x616308 + head as usize * 0x800, 0x111, 0x11);
    // The measured update has a fresh completion epoch after empty bootstrap.
    write_words(regs,total,notifier,&[0,0,0,0])?;
    let notifier_before = read_word(regs, total, notifier)?;
    let mut put = 0;
    let mut init = alloc::vec![(0x88, 2)];
    init.extend(methods);
    init.extend([(0x84, 0x90000000), (0x80, 0)]);
    submit(regs, total, evo, &mut put, &init)?;
    let after = complete(
        regs,
        total,
        notifier,
        &limits,
        &coefficients,
        (head, u32::from(route.sor)),
        &scripts,
    )?;
    crate::firmware_writes::handoff();
    let h = head as usize * 0x300;
    let skipped_address = u64::from(regs.read(0x640460 + h)) << 8;
    write_words(regs, total, notifier, &[0, 0, 0, 0])?;
    submit(
        regs,
        total,
        evo,
        &mut put,
        &[
            (
                0x460 + head * 0x300,
                (layout.objects[1].range.start >> 8) as u32,
            ),
            (0x84, 0x90000000),
        ],
    )?;
    modeset::wait(regs, 0x640004, u32::MAX, put)?;
    regs.delay_us(40000);
    let skipped_notifier = read_word(regs, total, notifier)?;
    if skipped_address != surface.start
        || u64::from(regs.read(0x640460 + h)) << 8 != surface.start
        || skipped_notifier != 0
    {
        return Err("suppressed native update changed active binding or completion");
    }
    submit(
        regs,
        total,
        evo,
        &mut put,
        &[
            (0x460 + head * 0x300, (surface.start >> 8) as u32),
            (0x80, 0),
        ],
    )?;
    let clean = complete(
        regs,
        total,
        notifier,
        &limits,
        &coefficients,
        (head, u32::from(route.sor)),
        &scripts,
    )?;
    // A bounded BAR1 view of owned scanout storage; general VM allocation is M5.
    let bar_inst = instance + 0x2000;
    let directory = instance + 0x3000;
    let table = instance + 0x4000;
    write_words(
        regs,
        total,
        bar_inst + 0x200,
        &[directory as u32, 0, (modeset::BAR1_WINDOW-1) as u32, 0],
    )?;
    write_words(regs, total, directory, &[((table >> 8) as u32) | 1, 0])?;
    {
        let mut p = memory::Pramin::new(regs, total);
        for i in 0..1024 {
            let pte = if i < pages {
                ((base + (i << page)) >> 8) | 1
            } else {
                2
            };
            p.write(table + i * 8, pte as u32)?;
            p.write(table + i * 8 + 4, (pte >> 32) as u32)?;
        }
    }
    modeset::bar_flush(regs)?;
    let old_bar = regs.read(0x1704);
    regs.write(0x1704, 0x80000000 | (bar_inst >> 12) as u32);
    let mut free = false;
    for _ in 0..20000 {
        if regs.read(0x100c80) & 0x00ff0000 != 0 {
            free = true;
            break;
        }
        regs.delay_us(100);
    }
    if !free {
        return Err("BAR1 invalidation queue has no free slot");
    }
    regs.write(0x100cb8, (directory >> 8) as u32);
    regs.write(0x100cbc, 0x80000005);
    modeset::wait(regs, 0x100c80, 0x8000, 0x8000)?;
    modeset::bar1_wait(regs)?;
    let mut digest = crate::block::install::sha256::Sha256::new();
    let mut data_bytes = 0usize;
    for y in 0..t.height {
        let mut line = String::new();
        let mut runs: Vec<(usize, u32)> = Vec::new();
        for x in 0..layout.pitch / 4 {
            // SAFETY: BAR1 now maps these bounded owned VRAM pages, WC on each alias.
            let actual = unsafe {
                ((pointer + y as usize * layout.pitch as usize + x as usize * 4) as *const u32)
                    .read_volatile()
            };
            let expected = 0xff000000
                | (seed
                    .wrapping_add(y * 257)
                    .wrapping_add((x as u32 / 64) * 0x10203)
                    & 0xffffff);
            if actual != expected {
                let offset=u64::from(y)*layout.pitch+x*4;
                let physical=read_word(regs,total,surface.start+offset)?;
                let pd=read_word(regs,total,bar_inst+0x200)?;
                let pde=read_word(regs,total,directory)?;
                let pte=read_word(regs,total,table+((displacement as u64+offset)>>page)*8)?;
                crate::serial_println!("GT710_BAR1_REFUSAL offset={} expected={:#x} actual={:#x} pramin={:#x} block={:#x} page={} pdb={:#x} pde={:#x} pte={:#x} mmu={:#x} firmware_writes={}",
                    offset,expected,actual,physical,regs.read(0x1704),page,pd,pde,pte,regs.read(0x100c80),crate::firmware_writes::count());
                return Err("native BAR1 complete read-back differs from physical pattern");
            }
            digest.update(&actual.to_le_bytes());
            data_bytes += 4;
            if let Some((n, _)) = runs.last_mut().filter(|(_, v)| *v == actual) {
                *n += 1;
            } else {
                runs.push((1, actual));
            }
        }
        for (i, (n, v)) in runs.iter().enumerate() {
            if i != 0 {
                line.push(',');
            }
            let _ = write!(line, "{n:x}:{v:08x}");
        }
        crate::serial_println!("GT710_PIX {} {}", y, line);
    }
    let raster_before = regs.read(0x616340 + head as usize * 0x800);
    regs.delay_us(50000);
    let raster_after = regs.read(0x616340 + head as usize * 0x800);
    let mut active = String::new();
    for r in [
        0x404, 0x414, 0x418, 0x41c, 0x420, 0x450, 0x460, 0x468, 0x46c, 0x470, 0x474,
    ] {
        if !active.is_empty() {
            active.push(',');
        }
        let reg = 0x640000 + h + r;
        let _ = write!(active, "[{},{}]", reg, regs.read(reg));
    }
    let sor_reg = 0x640200 + route.sor as usize * 32;
    let _ = write!(active, ",[{},{}]", sor_reg, regs.read(sor_reg));
    let timing=format!("{{\"width\":{},\"height\":{},\"clock_khz\":{},\"hsync_start\":{},\"hsync_end\":{},\"htotal\":{},\"vsync_start\":{},\"vsync_end\":{},\"vtotal\":{},\"flags\":{}}}",t.width,t.height,t.clock_khz,t.hsync_start,t.hsync_end,t.htotal,t.vsync_start,t.vsync_end,t.vtotal,t.flags);
    let report=format!(concat!("{{\"schema\":1,\"phase\":\"native\",\"bdf\":\"{:02x}:{:02x}.{}\",",
        "\"head\":{},\"sor\":{},\"protocol\":{},\"timing\":{},\"surface\":{},\"pitch\":{},\"seed\":{},\"active\":[{}],\"quiesce_before\":{:?},\"quiesce_after\":{:?},",
        "\"notifier_before\":{},\"notifier_after\":{},\"put\":{},\"get\":{},\"errors\":{},\"underflow\":{},",
        "\"power\":{},\"power_status\":{},\"raster_before\":{},\"raster_after\":{},\"instance\":{},\"push\":{},",
        "\"skipped_address\":{},\"skipped_notifier\":{},\"clean_notifier\":{},\"firmware_writes\":{},",
        "\"bytes\":{},\"sha256\":\"{}\",\"bar1_before\":{},\"bar1_after\":{},\"pll_record\":\"{}\",\"pll_register\":{},\"pll_reference\":{},\"pll_coefficients\":{},\"pll_fraction\":{}}}"),
        device.bus,device.device,device.function,head,route.sor,protocol,timing,surface.start,layout.pitch,seed,active,quiesce_before,quiesce_after,
        notifier_before,after,put,regs.read(0x640004),regs.read(0x61009c),regs.read(0x616308+head as usize*0x800),
        regs.read(0x61c004+route.sor as usize*0x800),regs.read(0x61c030+route.sor as usize*0x800),raster_before,raster_after,instance,evo,
        skipped_address,skipped_notifier,clean,crate::firmware_writes::count()-firmware_baseline,data_bytes,super::hex(&digest.finalize()),old_bar,regs.read(0x1704),super::hex(pll_record),limits.reg,limits.reference,
        regs.read(limits.reg as usize+4),regs.read(limits.reg as usize+16));
    crate::serial_println!("GT710_MODE {}", report);
    Ok(ConsoleSurface {
        pointer,
        bytes: surface.size as usize,
        width: t.width as usize,
        height: t.height as usize,
        pitch: layout.pitch as usize,
        vram: surface.start,
        regs: regs.0,
        head,
        phys: device.bars[1].address + displacement as u64,
        firmware_baseline,
    })
}

pub fn console_binding(surface: &ConsoleSurface) -> Result<(), &'static str> {
    let regs = Registers(surface.regs);
    let h = surface.head as usize * 0x300;
    if u64::from(regs.read(0x640460 + h)) << 8 != surface.vram
        || regs.read(0x61009c) != 0
        || regs.read(0x616308 + surface.head as usize * 0x800) & 0x111 != 1
    {
        return Err("native console lost active binding or display health");
    }
    Ok(())
}
