//! Bounded context-image readback through the M6.2 channel and CE release path.
//! This wrapper reuses Channel::execute and its engine-ordered completion.
use super::*;

pub(in crate::gk208) struct Reader {
    channel: Channel,
    engine: Engine,
    bar: usize,
    bar_inst: u64,
    bar_dir: u64,
    pte: u64,
    old: [u32; 7],
}
impl Reader {
    pub(in crate::gk208) fn new(
        regs: &mut Registers,
        device: &pci::Device,
        layout: &mut memory::Layout,
        console: &super::super::ConsoleSurface,
        backing: &[(u64, Allocation)],
    ) -> Result<Self, &'static str> {
        let s = layout.allocator.stats();
        let total = s.reserved + s.charged + s.free;
        let engine = discover(regs)?;
        if regs.read(0x259c) != 0 || regs.read(0x800000) != 0 || regs.read(0x800008) != 0 {
            return Err("context readback CE inherited or faulted state");
        }
        let status = system_dma::translation_status()?;
        let userd = layout.allocator.allocate(4096, 4096, Kind::Engine)?;
        let mut channel = Channel::new(regs, layout, total, 0, &status, userd)?;
        for (va, a) in backing {
            channel.context.map(
                &mut layout.allocator,
                &mut VmIo { regs, total },
                *va,
                *a,
                flags(),
            )?;
        }
        let native = layout
            .objects
            .iter()
            .find(|o| o.name == "instance")
            .ok_or("native BAR instance absent")?
            .range
            .start;
        let (bar_inst, bar_dir) = (native + 0x2000, native + 0x3000);
        let pte = native + 0x4000 + (SLOT / 4096) * 8;
        if read(regs, total, pte)? != 0 || read(regs, total, pte + 4)? != 0 {
            return Err("context readback USERD BAR alias occupied");
        }
        let (_, displacement, _) = modeset::bar1_view(
            layout.objects[0].range.start,
            layout.objects[0].range.size,
            device.bars[1].size,
            17,
        )?;
        let bar = console.pointer - displacement;
        let old = [
            regs.read(0x2254),
            regs.read(0x2140),
            regs.read(0x204),
            regs.read(0x2630),
            regs.read(0x800004),
            regs.read(engine.base + 0x904),
            regs.read(0x200),
        ];
        regs.write(0x2140, 0);
        regs.write(engine.base + 0x904, 0);
        regs.mask(0x200, 1 << engine.reset, 1 << engine.reset);
        regs.mask(0x204, 1 << engine.pbdma, 1 << engine.pbdma);
        regs.write(0x2254, 0x10000000 | (SLOT >> 12) as u32);
        regs.write(engine.base + 0x908, 7);
        regs.write(engine.base + 0xf14, 0);
        channel.activate(regs, total, &engine, bar_inst, bar_dir, pte)?;
        Ok(Self {
            channel,
            engine,
            bar,
            bar_inst,
            bar_dir,
            pte,
            old,
        })
    }
    pub(in crate::gk208) fn image(
        &mut self,
        regs: &mut Registers,
        total: u64,
        va: u64,
        bytes: usize,
    ) -> Result<[Vec<u8>; 2], &'static str> {
        if bytes == 0 || bytes > 1 << 20 {
            return Err("invalid context readback extent");
        }
        let mut snapshots = [vec![0; bytes], vec![0; bytes]];
        for (n, poison) in [0x55, 0xaa].into_iter().enumerate() {
            for start in (0..bytes).step_by(SIZE) {
                let count = SIZE.min(bytes - start);
                system_fill(&self.channel, poison);
                self.channel.execute(
                    regs,
                    total,
                    &self.engine,
                    self.bar,
                    rect(
                        va + start as u64,
                        SYSTEM,
                        count as u32,
                        1,
                        count as u32,
                        count as u32,
                    ),
                )?;
                observation::read(
                    &*self.channel.pages,
                    0,
                    &mut snapshots[n][start..start + count],
                );
            }
        }
        // Compare both system-memory snapshots, including source bytes whose
        // values happen to equal a destination poison.
        if snapshots[0] != snapshots[1] {
            return Err("context CE P/~P readbacks differ");
        }
        Ok(snapshots)
    }
    pub(in crate::gk208) fn finish(
        mut self,
        regs: &mut Registers,
        layout: &mut memory::Layout,
    ) -> Result<(), &'static str> {
        let s = layout.allocator.stats();
        let total = s.reserved + s.charged + s.free;
        self.channel.drain(regs, &self.engine)?;
        words(regs, total, self.pte, &[0, 0])?;
        modeset::activate_bar1(regs, self.bar_inst, self.bar_dir)?;
        let userd = self.channel.userd;
        self.channel.retire(regs, layout, total)?;
        layout.allocator.release(userd)?;
        regs.write(0x2254, self.old[0]);
        regs.write(0x2140, self.old[1]);
        regs.write(0x204, self.old[2]);
        regs.mask(
            0x2630,
            1 << self.engine.run,
            self.old[3] & (1 << self.engine.run),
        );
        regs.write(0x800004, self.old[4]);
        regs.write(self.engine.base + 0x904, self.old[5]);
        regs.mask(
            0x200,
            1 << self.engine.reset,
            self.old[6] & (1 << self.engine.reset),
        );
        Ok(())
    }
}
