//! Serialized bring-up channels for device-executed VM and CE checks.
//! IRQs remain masked; this boot-CPU owner polls and decodes outside top halves.
use super::{channel::{VmIo, read, wait as fifo_wait, elapsed}, copy::{self, Rect}, inventory::{words,stats},
    lifetime::{Context, Consumer}, memory::{self, allocator::{Allocation,Kind}}, modeset::{self,Io},
    system_dma, vm::Flags, Registers};
use crate::{arch_impl::x86_64::timer,drivers::pci};
use alloc::{format,vec,vec::Vec,string::String};
use core::mem::ManuallyDrop;
const COMMAND:u64=0x100000;
const SOURCE:u64=0x400000;
const DEST:u64=0x500000;
const STAGE:u64=0x600000;
const SYSTEM:u64=0x800000;
const SIZE:usize=8192;
const SLOT:u64=(8<<20)-4096;
fn wait(regs:&mut Registers,r:usize,mask:u32,value:u32,budget:u64)->Result<(),&'static str> {
    let result=fifo_wait(regs,r,mask,value,budget);
    if result.is_err() {
        crate::serial_println!("GT710_CE_WAIT register={:#x} mask={:#x} wanted={:#x} observed={:#x} fault={:#x} freeze={:#x} exception={:#x} preempt={:#x}",
            r,mask,value,regs.read(r),regs.read(0x259c),regs.read(0x2630),regs.read(0x262c),regs.read(0x2634));
    }
    result
}
struct Engine { engine:u32,run:u32,pbdma:usize,base:usize,reset:u32,fault:u32 }
fn discover(regs:&mut Registers)->Result<Engine,&'static str> {
    let (mut engine,mut run,mut base,mut reset,mut fault)=(None,None,None,None,None);
    for i in 0..64 {
        let w=regs.read(0x22700+i*4);
        match w&3 {
            0=>continue,
            1=>{base=Some((w&0xfff000) as usize);if w&4!=0 {fault=Some((w>>3)&127);}},
            2=>{if w&32!=0 {engine=Some((w>>26)&15);}if w&16!=0 {run=Some((w>>21)&15);}if w&4!=0 {reset=Some((w>>9)&31);}},
            _=>(),
        }
        if w&0x80000000==0 {
            if w&3==3 && (w&0x7ffffffc)>>2==1 {
                let run=run.ok_or("CE runlist absent")?;
                let pbdma=(0..32).find(|i|regs.read(0x2390+i*4)&(1<<run)!=0).ok_or("CE PBDMA absent")?;
                // GK208 omits DATA words. gk104 CE0 has register base
                // 104000h and gk104_fifo_mmu_fault_engine identifies unit 15h.
                return Ok(Engine{engine:engine.ok_or("CE engine absent")?,run,pbdma,
                    base:base.unwrap_or(0x104000),reset:reset.ok_or("CE reset bit absent")?,fault:fault.unwrap_or(0x15)});
            }
            engine=None;run=None;base=None;reset=None;fault=None;
        }
    }
    Err("enumerated CE0 unavailable")
}
struct Channel {
    id:u32, context:Context, commands:Allocation,source:Allocation,dest:Allocation,stage:Allocation,
    pages:ManuallyDrop<system_dma::Pages>, epoch:u64, put:u32, active:bool,
}
fn flags()->Flags {Flags{volatile:true,..Flags::default()}}
impl Channel {
    fn new(regs:&mut Registers,layout:&mut memory::Layout,total:u64,id:u32,status:&[u32])->Result<Self,&'static str> {
        let mut io=VmIo{regs,total};let mut context=Context::new(&mut layout.allocator,&mut io)?;
        let commands=layout.allocator.allocate(65536,4096,Kind::Engine)?;
        let source=layout.allocator.allocate(SIZE as u64,4096,Kind::Engine)?;
        let dest=layout.allocator.allocate(SIZE as u64,4096,Kind::Engine)?;
        let stage=layout.allocator.allocate(SIZE as u64,4096,Kind::Engine)?;
        for (va,a) in [(COMMAND,commands),(SOURCE,source),(DEST,dest),(STAGE,stage)] {
            context.map(&mut layout.allocator,&mut io,va,a,flags())?;
        }
        let pages=ManuallyDrop::new(system_dma::Pages::new(2,status)?);
        context.map_system(&mut layout.allocator,&mut io,SYSTEM,&[pages.address(0),pages.address(1)])?;
        for off in (0..65536).step_by(4096) {words(regs,total,commands.range.start+off,&[0;1024])?;}
        let instance=context.space().instance.range.start;
        let userd=commands.range.start+12288+u64::from(id)*512;
        for (offset,value) in [(0x08,userd as u32),(0x0c,(userd>>32) as u32),(0x10,0xface),
            (0x30,0xfffff902),(0x48,COMMAND as u32),(0x4c,9<<16),(0x84,0x20400000),
            (0x94,0x30000fff),(0x9c,0x100),(0xac,0x1f),(0xe4,0x20),(0xe8,0),
            (0xb8,0xf8000000),(0xf8,0x10003080),(0xfc,0x10000010)] {
            words(regs,total,instance+offset,&[value])?;
        }
        words(regs,total,commands.range.start+16384,&[id,0])?;
        Ok(Self{id,context,commands,source,dest,stage,pages,epoch:timer::rdtsc()|1,put:0,active:false})
    }
    fn activate(&mut self,regs:&mut Registers,total:u64,e:&Engine,bar_inst:u64,bar_dir:u64,pte:u64)->Result<(),&'static str> {
        if self.active {return Ok(());}
        words(regs,total,pte,&[(((self.commands.range.start+12288)>>8)|1) as u32,0])?;
        modeset::activate_bar1(regs,bar_inst,bar_dir)?;
        unsafe {self.context.admit_device()?;}
        let ch=self.id as usize*8;
        regs.mask(0x800004+ch,0xf0000,e.run<<16);
        regs.write(0x800000+ch,0x80000000|(self.context.space().instance.range.start>>12) as u32);
        regs.mask(0x800004+ch,0x400,0x400);
        regs.mask(0x2630,1<<e.run,0);
        regs.write(0x2270,((self.commands.range.start+16384)>>12) as u32);
        regs.write(0x2274,(e.run<<20)|1);
        wait(regs,0x2284+e.run as usize*8,0x100000,0,2_000_000)?;
        self.active=true;
        Ok(())
    }
    fn submit(&mut self,regs:&mut Registers,total:u64,bar:usize,rect:Rect,publish:bool)->Result<u32,&'static str> {
        if !self.active || self.put>=500 {return Err("CE ring unavailable");}
        let seq=self.put+1;
        let command=copy::encode(rect,COMMAND+8192,self.epoch,seq)?;
        // Reuse command storage only after the preceding engine completion.
        words(regs,total,self.commands.range.start+4096,&command)?;
        words(regs,total,self.commands.range.start+u64::from(self.put)*8,
            &[(COMMAND+4096) as u32,((command.len() as u32)<<10)|0x100])?;
        modeset::bar_flush(regs)?;
        if publish {
            unsafe {((bar+SLOT as usize+self.id as usize*512+0x8c) as *mut u32).write_volatile(seq);}
            crate::gpu_cache::drain_wc();let _=regs.read(0x2254); self.put=seq;
        }
        Ok(seq)
    }
    fn completed(&self,regs:&mut Registers,total:u64,e:&Engine,seq:u32,budget:u64)->Result<(bool,u64),&'static str> {
        let start=timer::rdtsc();
        loop {
            let addr=self.commands.range.start+8192;
            let value=read(regs,total,addr)?;
            let epoch=u64::from(read(regs,total,addr+4)?)|u64::from(read(regs,total,addr+8)?)<<32;
            let p=e.pbdma*0x2000;
            let accepted=regs.read(0x259c)==0 && value==seq && epoch==self.epoch && regs.read(0x40014+p)==self.put
                && regs.read(0x40120+p)&0x2fff==0x2000|self.id;
            if accepted || elapsed(start)>=budget {return Ok((accepted,elapsed(start)));}
            if regs.read(0x259c)!=0 {return Ok((false,elapsed(start)));}
            regs.delay_us(10);
        }
    }
    fn execute(&mut self,regs:&mut Registers,total:u64,e:&Engine,bar:usize,r:Rect)->Result<u64,&'static str> {
        let ticket=self.context.hold(Consumer::Queued)?;
        let seq=self.submit(regs,total,bar,r,true)?;
        let (done,time)=self.completed(regs,total,e,seq,2_000_000)?;
        if !done {
            crate::serial_println!("GT710_CE_ERROR channel={} seq={} sem={} get={} current={:#x} fifo={:#x} fault={:#x} ce={:#x} launch={:#x} pbdma={:#x}/{:#x} method={:#x} data={:#x}",
                self.id,seq,read(regs,total,self.commands.range.start+8192)?,regs.read(0x40014+e.pbdma*0x2000),regs.read(0x40120+e.pbdma*0x2000),regs.read(0x2100),regs.read(0x259c),regs.read(e.base+0x908),regs.read(e.base+0xf14),regs.read(0x40108+e.pbdma*0x2000),regs.read(0x40148+e.pbdma*0x2000),regs.read(0x40150+e.pbdma*0x2000),regs.read(0x40154+e.pbdma*0x2000));
            return Err("CE completion failed; backing retained");
        }
        unsafe {self.context.finish_device(ticket)?;}
        if regs.read(e.base+0x908)&7!=0 || regs.read(0x40108+e.pbdma*0x2000)!=0
            || regs.read(0x40148+e.pbdma*0x2000)!=0 {return Err("CE hardware error");}
        Ok(time)
    }
    fn drain(&mut self,regs:&mut Registers,e:&Engine)->Result<(),&'static str> {
        if !self.active {return Ok(());}
        regs.mask(0x2630,1<<e.run,1<<e.run);
        regs.mask(0x800004+self.id as usize*8,0x800,0x800);
        regs.write(0x2634,self.id);
        wait(regs,0x2634,0x100000,0,2_000_000)?;
        regs.write(0x2270,((self.commands.range.start+16384)>>12) as u32);
        regs.write(0x2274,e.run<<20);
        wait(regs,0x2284+e.run as usize*8,0x100000,0,2_000_000)?;
        wait(regs,0x3080+e.pbdma*4,0xe000,0,2_000_000)?;
        wait(regs,0x2640+e.engine as usize*8,0x80000000,0,100_000)?;
        regs.write(0x800000+self.id as usize*8,0);
        if regs.read(0x800000+self.id as usize*8)!=0 {return Err("CE unbind failed");}
        unsafe {self.context.confirm_drain();}
        self.active=false;Ok(())
    }
    fn retire(mut self,regs:&mut Registers,layout:&mut memory::Layout,total:u64)->Result<(),&'static str> {
        if self.active {return Err("active CE retirement refused");}
        self.context.retire(&mut layout.allocator,&mut VmIo{regs,total})?;
        for a in [self.commands,self.source,self.dest,self.stage] {layout.allocator.release(a)?;}
        unsafe {ManuallyDrop::drop(&mut self.pages);}
        Ok(())
    }
}
fn pattern(i:usize,seed:u32)->u8 {
    let mut x=(i as u32)^seed;x^=x>>16;x=x.wrapping_mul(0x7feb352d);x^=x>>15;
    x=x.wrapping_mul(0x846ca68b);((x^(x>>16))&255) as u8
}
fn fill(regs:&mut Registers,total:u64,a:u64,data:&[u8])->Result<(),&'static str> {
    let mut p=memory::Pramin::new(regs,total);
    for (i,b) in data.chunks_exact(4).enumerate() {p.write(a+i as u64*4,u32::from_le_bytes(b.try_into().unwrap()))?;}
    Ok(())
}
fn rect(src:u64,dst:u64,width:u32,height:u32,sp:u32,dp:u32)->Rect {
    Rect{src,dst,width,height,src_pitch:sp,dst_pitch:dp}
}
fn system_fill(c:&Channel,byte:u8) {
    for i in 0..2 {unsafe {core::ptr::write_bytes(c.pages.va(i) as *mut u8,byte,4096);}}
    c.pages.publish();
}
fn system_bytes(c:&Channel)->Vec<u8> {
    c.pages.observe();let mut data=Vec::with_capacity(SIZE);
    for i in 0..2 {unsafe {data.extend_from_slice(core::slice::from_raw_parts(c.pages.va(i) as *const u8,4096));}}
    data
}
fn emit_bytes(id:usize,pass:usize,data:&[u8]) {
    for (n,b) in data.chunks(256).enumerate() {
        crate::serial_println!("GT710_CE_BYTES {} {} {} {}",id,pass,n*256,super::hex(b));
    }
}
#[derive(Clone,Copy)]
struct Case {name:&'static str,src_offset:u32,dst_offset:u32,width:u32,height:u32,sp:u32,dp:u32,upload:bool,overlap:bool}
fn run_case(regs:&mut Registers,total:u64,e:&Engine,bar:usize,c:&mut Channel,id:usize,seed:u32,k:Case)->Result<String,&'static str> {
    let initial:Vec<u8>=(0..SIZE).map(|i|pattern(i,seed)).collect();
    let mut expected=if k.overlap {initial.clone()} else {vec![0xcc;SIZE]};
    for y in 0..k.height as usize {
        let s=k.src_offset as usize+y*k.sp as usize;let d=k.dst_offset as usize+y*k.dp as usize;
        expected[d..d+k.width as usize].copy_from_slice(&initial[s..s+k.width as usize]);
    }
    fill(regs,total,c.source.range.start,&initial)?;
    let destination=if k.overlap {initial.clone()} else {vec![0xcc;SIZE]};
    fill(regs,total,c.dest.range.start,&destination)?;
    modeset::bar_flush(regs)?;
    if k.upload {
        for i in 0..2 {unsafe {core::ptr::copy_nonoverlapping(initial[i*4096..].as_ptr(),c.pages.va(i) as *mut u8,4096);}}
        c.pages.publish();
    }
    let src=if k.upload {SYSTEM} else if k.overlap {DEST} else {SOURCE};
    let mut transfer_us=0;
    if k.overlap {
        transfer_us+=c.execute(regs,total,e,bar,rect(DEST,STAGE,SIZE as u32,1,SIZE as u32,SIZE as u32))?;
    }
    transfer_us+=c.execute(regs,total,e,bar,rect(
        (if k.overlap {STAGE} else {src})+u64::from(k.src_offset),DEST+u64::from(k.dst_offset),k.width,k.height,k.sp,k.dp))?;
    let mut releases=Vec::new();
    for (pass,poison) in [0x55,0xaa].into_iter().enumerate() {
        system_fill(c,poison);
        transfer_us+=c.execute(regs,total,e,bar,rect(DEST,SYSTEM,SIZE as u32,1,SIZE as u32,SIZE as u32))?;
        let actual=system_bytes(c);
        emit_bytes(id,pass,&actual);
        if actual!=expected {return Err("complete CE byte comparison failed");}
        releases.push(c.put);
    }
    crate::serial_println!("GT710_CE_STAGE case={} channel={} sequence={} elapsed_us={}",k.name,c.id,c.put,transfer_us);
    Ok(format!("{{\"id\":{},\"name\":\"{}\",\"channel\":{},\"epoch\":{},\"sequence\":{},\"size\":{},\"seed\":{},\"width\":{},\"height\":{},\"src_pitch\":{},\"dst_pitch\":{},\"src_offset\":{},\"dst_offset\":{},\"fill\":204,\"overlap\":{},\"upload\":{},\"poisons\":[85,170],\"releases\":{:?},\"elapsed_us\":{},\"source\":{},\"dest\":{},\"instance\":{},\"directory\":{}}}",id,k.name,c.id,c.epoch,c.put,SIZE,seed,k.width,k.height,k.sp,k.dp,k.src_offset,k.dst_offset,k.overlap,k.upload,releases,transfer_us,c.source.range.start,c.dest.range.start,c.context.space().instance.range.start,c.context.space().directory.range.start))
}
pub fn probe(regs:&mut Registers,device:&pci::Device,layout:&mut memory::Layout,console:&super::ConsoleSurface)->Result<(),&'static str> {
    let baseline=layout.allocator.stats();let total=baseline.reserved+baseline.charged+baseline.free;
    let e=discover(regs)?;
    crate::serial_println!("GT710_CE_STAGE discovery engine={} run={} base={:#x} reset={} fault={}",e.engine,e.run,e.base,e.reset,e.fault);
    if regs.read(0x259c)!=0 || regs.read(0x800000)!=0 || regs.read(0x800008)!=0 {return Err("CE inherited or faulted state");}
    let status=system_dma::translation_status()?;
    let mut a=Channel::new(regs,layout,total,0,&status)?;
    let mut b=Channel::new(regs,layout,total,1,&status)?;
    let native=layout.objects.iter().find(|o|o.name=="instance").ok_or("native BAR instance absent")?.range.start;
    let (bar_inst,bar_dir)=(native+0x2000,native+0x3000);
    let pte=native+0x4000+(SLOT/4096)*8;
    if read(regs,total,pte)?!=0 {return Err("CE USERD BAR alias occupied");}
    let (_,displacement,_)=modeset::bar1_view(layout.objects[0].range.start,layout.objects[0].range.size,device.bars[1].size,17)?;
    let bar=console.pointer-displacement;
    let (old_userd,old_intr,old_enabled)=(regs.read(0x2254),regs.read(0x2140),regs.read(0x204));
    regs.write(0x2140,0);regs.write(e.base+0x904,0);
    regs.mask(0x200,1<<e.reset,1<<e.reset);
    regs.mask(0x204,1<<e.pbdma,1<<e.pbdma);
    regs.write(0x2254,0x10000000|(SLOT>>12) as u32);
    regs.write(e.base+0x908,7);regs.write(e.base+0xf14,0);
    let mut cases=Vec::new();
    let full=Case{name:"same-va-a",src_offset:0,dst_offset:0,width:8192,height:1,sp:8192,dp:8192,upload:false,overlap:false};
    let seed=timer::rdtsc() as u32;
    a.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    for k in [full,Case{name:"byte",src_offset:4095,dst_offset:4096,width:1,..full},
        Case{name:"unaligned",src_offset:3,dst_offset:7,width:4097,..full},
        Case{name:"rectangle",src_offset:17,dst_offset:4093,width:257,height:3,sp:263,dp:271,..full},
        Case{name:"upload",upload:true,src_offset:4093,dst_offset:1,width:2051,..full},
        Case{name:"overlap-forward",overlap:true,src_offset:0,dst_offset:3,width:8189,..full},
        Case{name:"overlap-backward",overlap:true,src_offset:3,dst_offset:0,width:8189,..full}] {
        cases.push(run_case(regs,total,&e,bar,&mut a,cases.len(),seed,k)?);
    }
    // Small nonce-selected adversarial lengths, with a page crossing in each.
    for i in 0..4 {
        let width=1+((seed.rotate_left(i*7))%4095);
        let k=Case{name:"random",src_offset:4093,dst_offset:4095,width,..full};
        cases.push(run_case(regs,total,&e,bar,&mut a,cases.len(),seed^i,k)?);
    }
    // Withhold GPPut, then plant an earlier epoch in the real completion record.
    let seq=a.submit(regs,total,bar,rect(SOURCE,DEST,8192,1,8192,8192),false)?;
    let (accepted,withheld_us)=a.completed(regs,total,&e,seq,10000)?;
    if accepted {return Err("withheld CE completion accepted");}
    words(regs,total,a.commands.range.start+8192,&[a.put,(a.epoch-1) as u32,((a.epoch-1)>>32) as u32])?;
    modeset::bar_flush(regs)?;
    let (accepted,stale_us)=a.completed(regs,total,&e,a.put,10000)?;
    if accepted {return Err("stale CE epoch accepted");}
    cases.push(run_case(regs,total,&e,bar,&mut a,cases.len(),seed,Case{name:"clean-next",..full})?);
    a.drain(regs,&e)?;
    b.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    cases.push(run_case(regs,total,&e,bar,&mut b,cases.len(),!seed,Case{name:"same-va-b",..full})?);
    b.drain(regs,&e)?;
    // Replace A's backing only while its channel is drained, with per-PDB invalidation.
    let replacement=layout.allocator.allocate(SIZE as u64,4096,Kind::Engine)?;
    let old_source=a.source;
    a.context.remap(&layout.allocator,&mut VmIo{regs,total},SOURCE,replacement,flags())?;
    a.source=replacement;layout.allocator.release(old_source)?;
    a.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    cases.push(run_case(regs,total,&e,bar,&mut a,cases.len(),seed^0x91827364,Case{name:"remapped-a",..full})?);
    a.drain(regs,&e)?;
    b.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    // B's source and destination are checked without any CPU refill after A's remap.
    for (pass,poison) in [0x55,0xaa].into_iter().enumerate() {
        system_fill(&b,poison);b.execute(regs,total,&e,bar,rect(SOURCE,SYSTEM,8192,1,8192,8192))?;
        let bytes=system_bytes(&b);emit_bytes(cases.len(),pass,&bytes);
        if bytes!=(0..SIZE).map(|i|pattern(i,!seed)).collect::<Vec<_>>() {return Err("other channel source changed");}
    }
    cases.push(format!("{{\"id\":{},\"name\":\"unaffected-b\",\"channel\":1,\"epoch\":{},\"sequence\":{},\"size\":8192,\"seed\":{},\"width\":8192,\"height\":1,\"src_pitch\":8192,\"dst_pitch\":8192,\"src_offset\":0,\"dst_offset\":0,\"fill\":204,\"overlap\":false,\"upload\":false,\"poisons\":[85,170],\"releases\":[{},{}],\"elapsed_us\":0,\"source\":{},\"dest\":{},\"instance\":{},\"directory\":{}}}",cases.len(),b.epoch,b.put,!seed,b.put-1,b.put,b.source.range.start,b.dest.range.start,b.context.space().instance.range.start,b.context.space().directory.range.start));
    b.drain(regs,&e)?;
    a.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    // This VA has an allocated SPT but no PTE, and is bounded to a single byte.
    let invalid=SOURCE+SIZE as u64+4096;
    let held=a.context.hold(Consumer::Queued)?;
    let badseq=a.submit(regs,total,bar,rect(invalid,DEST,1,1,1,1),true)?;
    let start=timer::rdtsc();
    while regs.read(0x259c)==0 {
        if elapsed(start)>=2_000_000 {return Err("unmapped CE address did not fault");}
        regs.delay_us(10);
    }
    let (fault_mask,faults)=super::vm::faults(&mut VmIo{regs,total});
    let f=faults.iter().find(|f|u32::from(f.unit)==e.fault).ok_or("CE fault unit mismatch")?;
    crate::serial_println!("GT710_CE_STAGE fault mask={:#x} unit={} instance={:#x} address={:#x} raw={:?}",fault_mask,f.unit,f.instance,f.address,f.raw);
    if f.instance!=a.context.space().instance.range.start || f.address!=invalid || f.reason!=2 || f.write {
        return Err("unmapped CE fault attribution mismatch");
    }
    if a.completed(regs,total,&e,badseq,10000)?.0 {return Err("faulted CE request reported success");}
    let fault_instance=f.instance;let fault_raw=f.raw;
    if !a.context.attribute(f) || a.context.holds()[0]!=1 {return Err("fault backing hold lost");}
    // Reset only this enumerated engine. Scheduling stays blocked and backing is
    // retained until reset read-back, idle engine and completed removal agree.
    let reset_start=timer::rdtsc();
    regs.mask(0x2630,1<<e.run,1<<e.run);
    regs.mask(0x800004,0x800,0x800);
    // A fault stops runlist progress. Reset before the update, then clear its
    // exception and allow scheduling before waiting (MIT nouveau runl.c RC).
    regs.mask(0x200,1<<e.reset,0);let disabled=regs.read(0x200);
    regs.delay_us(50);regs.mask(0x200,1<<e.reset,1<<e.reset);let enabled=regs.read(0x200);
    regs.write(0x259c,fault_mask);regs.write(0x2100,0x10000000);
    regs.write(0x2270,((a.commands.range.start+16384)>>12) as u32);
    regs.write(0x2274,e.run<<20);
    regs.write(0x262c,1<<e.run);
    regs.mask(0x2630,1<<e.run,0);
    wait(regs,0x2284+e.run as usize*8,0x100000,0,100000)?;
    regs.write(0x2634,0);wait(regs,0x2634,0x100000,0,100000)?;
    wait(regs,0x3080+e.pbdma*4,0xe000,0,100000)?;
    wait(regs,0x2640+e.engine as usize*8,0xc0000000,0,100000)?;
    regs.write(0x800000,0);
    let reset_us=elapsed(reset_start);
    if disabled&(1<<e.reset)!=0 || enabled&(1<<e.reset)==0 || reset_us>100000 || regs.read(0x259c)!=0 || regs.read(0x800000)!=0 {
        return Err("CE reset unconfirmed; backing retained");
    }
    unsafe {a.context.confirm_reset();}a.active=false;drop(held);
    a.retire(regs,layout,total)?;
    // Restore the mapping in a fresh channel after the confirmed engine reset.
    let mut a=Channel::new(regs,layout,total,0,&status)?;
    a.context.map(&mut layout.allocator,&mut VmIo{regs,total},invalid,a.source,flags())?;
    a.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    cases.push(run_case(regs,total,&e,bar,&mut a,cases.len(),seed,Case{name:"restored-a",..full})?);
    a.execute(regs,total,&e,bar,rect(invalid,DEST,8192,1,8192,8192))?;
    a.drain(regs,&e)?;
    b.activate(regs,total,&e,bar_inst,bar_dir,pte)?;
    cases.push(run_case(regs,total,&e,bar,&mut b,cases.len(),!seed,Case{name:"survivor-b",..full})?);
    b.drain(regs,&e)?;
    a.retire(regs,layout,total)?;b.retire(regs,layout,total)?;
    words(regs,total,pte,&[0,0])?;modeset::activate_bar1(regs,bar_inst,bar_dir)?;
    regs.write(0x2254,old_userd);regs.write(0x2140,old_intr);regs.write(0x204,old_enabled);
    if layout.allocator.stats()!=baseline {return Err("CE baseline reclamation mismatch");}
    crate::serial_println!("GT710_CE {{\"schema\":1,\"class\":41141,\"source_va\":{},\"system_va\":{},\"engine\":{},\"runlist\":{},\"reset_bit\":{},\"fault_unit\":{},\"cases\":[{}],\"withheld_us\":{},\"stale_us\":{},\"invalid\":{},\"fault_instance\":{},\"fault_raw\":{:?},\"fault_mask\":{},\"reset_us\":{},\"reset_disabled\":{},\"reset_enabled\":{},\"fault_after\":{},\"firmware_writes\":{},\"baseline\":{},\"after\":{},\"pgraph\":\"unmeasured\"}}",
        SOURCE,SYSTEM,e.engine,e.run,e.reset,e.fault,cases.join(","),withheld_us,stale_us,invalid,fault_instance,fault_raw,fault_mask,reset_us,disabled,enabled,regs.read(0x259c),crate::firmware_writes::count()-console.firmware_baseline,stats(baseline),stats(layout.allocator.stats()));
    Ok(())
}
