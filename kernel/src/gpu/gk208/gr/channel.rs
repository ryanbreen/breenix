//! Privileged graphics sessions on one owned runlist; waits poll.
//! Adapted hardware fields: MIT nouveau v6.8 FIFO gk208/gk110/gk104/gf100,
//! GR gf100 (channel copy/header), TOP gk104; MIT open-gpu-doc cla197/cla06f.
use alloc::{format, string::String, vec::Vec};
pub const SUBCHANNEL: u32 = 0;
const RELEASE: u32 = 0x1000f010;
const BOUND_US: u64 = 2_000_000;

pub fn bind() -> [u32; 2] {
    [0x20010000 | (SUBCHANNEL << 13), 0xa197]
}
pub fn report(target: u64, payload: u32) -> Result<[u32; 5], &'static str> {
    if target == 0 || target >= 1 << 40 || target & 3 != 0 {
        return Err("invalid GR report target");
    }
    Ok([
        0x200406c0 | (SUBCHANNEL << 13),
        (target >> 32) as u32,
        target as u32,
        payload,
        RELEASE,
    ])
}
/// Epoch halves precede the nonce through the same PGRAPH release method.
/// Withholding omits D itself, while A..C and host SET_REFERENCE still execute.
pub fn commands(
    target: u64,
    epoch: u64,
    nonce: u32,
    release: bool,
    reference: u32,
) -> Result<Vec<u32>, &'static str> {
    let mut words = bind().to_vec();
    if release {
        for (offset, value) in [(4, epoch as u32), (8, (epoch >> 32) as u32), (0, nonce)] {
            words.extend(report(
                target.checked_add(offset).ok_or("GR target overflow")?,
                value,
            )?);
        }
    } else {
        let r = report(target, nonce)?;
        words.extend([r[0] - (1 << 16), r[1], r[2], r[3]]);
    }
    words.extend([0x20010014, reference]);
    Ok(words)
}
#[derive(Clone, Copy)]
pub struct Observation {
    pub value: u32,
    pub epoch: u64,
    pub consumed: bool,
    pub elapsed_us: u64,
    pub accepted: bool,
}
/// Distinct receipt domains prevent a delayed channel release from certifying binding.
pub fn receipt_nonce(epoch: u64, binding: bool) -> u32 {
    let mixed = (epoch as u32 ^ (epoch >> 32) as u32) & !0x6000_0000;
    mixed | if binding { 0x2000_0000 } else { 0x4000_0000 }
}
pub trait Poll {
    fn snapshot(&mut self) -> Result<(u32, u64, bool), &'static str>;
    fn now_us(&mut self) -> u64;
    fn relax(&mut self);
}
pub fn wait(
    io: &mut impl Poll,
    epoch: u64,
    nonce: u32,
    budget: u64,
) -> Result<Observation, &'static str> {
    if epoch == 0 || nonce == 0 || budget == 0 || budget > BOUND_US {
        return Err("invalid GR completion request");
    }
    let start = io.now_us();
    loop {
        let (value, observed_epoch, consumed) = io.snapshot()?;
        let elapsed_us = io.now_us().saturating_sub(start);
        let accepted = consumed && value == nonce && observed_epoch == epoch;
        if accepted || elapsed_us >= budget {
            return Ok(Observation {
                value,
                epoch: observed_epoch,
                consumed,
                elapsed_us,
                accepted,
            });
        }
        io.relax();
    }
}
#[derive(Clone, Copy)]
pub struct Identity {
    pub id: u32,
    pub epoch: u64,
    pub instance: u64,
    pub top: [u32; 64],
    pub engine: u32,
    pub runlist: u32,
    pub bind: u32,
    pub state: u32,
    pub current_context: u32,
}
#[derive(Clone, Copy)]
pub struct Release {
    pub target: u64,
    pub poison: u32,
    pub nonce: u32,
    pub observed: u32,
    pub epoch: u64,
    pub elapsed_us: u64,
}
#[derive(Clone, Copy)]
pub struct Withheld {
    pub poison: u32,
    pub observation: Observation,
}
#[derive(Clone, Copy)]
pub struct Stale {
    pub nonce: u32,
    pub observation: Observation,
}
#[derive(Clone, Copy)]
pub struct Report {
    pub identity: Identity,
    pub releases: [Release; 2],
    pub withheld: Withheld,
    pub stale: Stale,
    pub faults: [[u32; 2]; 3],
    pub runlist_count: u32,
    pub binding: u32,
}
/// Append the channel fields to the measured U3-U5 JSON members, without braces.
/// The caller supplies firmware/context fields, allocator counters and markers.
pub fn format_record(context_fields: &str, r: &Report) -> String {
    let c = r.identity;
    let releases: Vec<String> = r.releases.iter().map(|v| format!(
        "{{\"class_id\":41367,\"method\":6924,\"word\":{},\"target\":{},\"poison\":{},\"nonce\":{},\"observed\":{},\"epoch\":{},\"elapsed_us\":{},\"bound_us\":{}}}",
        RELEASE, v.target, v.poison, v.nonce, v.observed, v.epoch, v.elapsed_us, BOUND_US)).collect();
    let w = r.withheld;
    let s = r.stale;
    format!("GT710_GR {{{},\"channel\":{{\"id\":{},\"epoch\":{},\"instance\":{},\"class_id\":41367,\"top\":{:?},\"engine\":{},\"runlist\":{},\"bind\":{},\"state\":{},\"current_context\":{}}},\"releases\":[{}],\"withheld_release\":{{\"poison\":{},\"observed\":{},\"accepted\":{}}},\"stale_release\":{{\"epoch\":{},\"nonce\":{},\"observed\":{},\"accepted\":{}}},\"faults\":{:?},\"teardown\":{{\"runlist_count\":{},\"binding\":{}}}}}",
        context_fields, c.id, c.epoch, c.instance, c.top, c.engine, c.runlist, c.bind, c.state, c.current_context,
        releases.join(","), w.poison, w.observation.value, w.observation.accepted,
        s.observation.epoch, s.nonce, s.observation.value, s.observation.accepted,
        r.faults, r.runlist_count, r.binding)
}

