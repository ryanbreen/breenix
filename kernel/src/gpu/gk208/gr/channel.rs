    impl Session {
        pub(in crate::gk208::gr) fn new(
            h: &mut Hardware<'_>,
            golden: &Golden,
            code_address: u64,
        ) -> Result<Self, &'static str> {
            Self::new_channel(h, golden, code_address, 0, None)
        }
        /// Open before publication so a failed second open leaves channel 0
        /// owned and unsubmitted. The caller returns it to Hardware::finish.
        pub(in crate::gk208::gr) fn open_second(
            &mut self, h: &mut Hardware<'_>, golden: &Golden, code_address: u64,
        ) -> Result<(), &'static str> {
            if self.bound || self.admitted || self.second.is_some() || self.report.identity.id != 0 {
                return Err("GR pair already published or second slot occupied");
            }
            let second = Self::new_channel(h, golden, code_address, 1, Some(self.userd + 512))?;
            self.second = Some(Box::new(second));
            Ok(())
        }
        fn new_channel(
            h: &mut Hardware<'_>, golden: &Golden, code_address: u64,
            id: u32, userd: Option<u64>,
        ) -> Result<Self, &'static str> {
            let top = core::array::from_fn(|i| h.regs.read(0x22700 + i * 4));
            let (mut engine, mut runlist, mut kind) = (None, None, None);
            let mut selected = None;
            for &w in &top {
                match w & 3 {
                    0 => continue,
                    2 => {
                        if w & 32 != 0 {
                            engine = Some((w >> 26) & 15);
                        }
                        if w & 16 != 0 {
                            runlist = Some((w >> 21) & 15);
                        }
                    }
                    3 => kind = Some((w & 0x7ffffffc) >> 2),
                    _ => (),
                }
                if w & 0x80000000 == 0 {
                    if kind == Some(0) {
                        selected = engine.zip(runlist);
                        break;
                    }
                    engine = None;
                    runlist = None;
                    kind = None;
                }
            }
            let (engine, runlist) = selected.ok_or("enumerated GR engine/runlist absent")?;
            // This boot probe runs after M6 has returned its channels. Refuse
            // inherited storage instead of replacing an occupied FIFO channel.
            for id in 0..1024 {
                if h.regs.read(0x800000 + id * 8) != 0 {
                    return Err("GR requires idle owned FIFO");
                }
            }
            let enabled = h.regs.read(0x204);
            h.regs.write(0x204, u32::MAX);
            let implemented = h.regs.read(0x204);
            h.regs.write(0x204, enabled);
            let pbdma = (0..32)
                .find(|i| {
                    implemented & (1 << i) != 0 && h.regs.read(0x2390 + i * 4) & (1 << runlist) != 0
                })
                .ok_or("GR runlist PBDMA absent")?;
            let native = h
                .layout
                .objects
                .iter()
                .find(|o| o.name == "instance")
                .ok_or("GR native BAR instance absent")?
                .range
                .start;
            let (bar_inst, bar_dir) = (native + 0x2000, native + 0x3000);
            let pte = native + 0x4000 + (SLOT / 4096) * 8;
            if read(h.regs, h.total, pte)? != 0 || read(h.regs, h.total, pte + 4)? != 0 {
                return Err("GR USERD BAR alias occupied");
            }
            let (_, displacement, _) = modeset::bar1_view(
                h.layout.objects[0].range.start,
                h.layout.objects[0].range.size,
                h.device.bars[1].size,
                17,
            )?;
            if displacement + h.console.bytes > SLOT as usize {
                return Err("GR USERD overlaps console");
            }
            let mut context = Context::new(
                &mut h.layout.allocator,
                &mut VmIo {
                    regs: h.regs,
                    total: h.total,
                },
            )?;
            let mut owned = Vec::new();
            let mut pages = None;
            let built = (|| {
                let flags = Flags {
                    privileged: true,
                    volatile: true,
                    ..Flags::default()
                };
                // Global buffers keep the golden VAs in both VMs. Only the MMIO
                // list is private: MIT GR gf100.c:364-426, 470-509.
                for &(va, a) in &h.backing {
                    if va == golden.buffers[3].va { continue; }
                    context.map(
                        &mut h.layout.allocator,
                        &mut VmIo {
                            regs: h.regs,
                            total: h.total,
                        },
                        va,
                        a,
                        // Shader fetch is an ordinary engine access, unlike the
                        // firmware-owned context buffers (MIT vmmgf100.c:259-265,
                        // 314-316; GR gf100.c:383). Keep program data unprivileged.
                        Flags { privileged: va != code_address, ..flags },
                    )?;
                }
                let commands = h.layout.allocator.allocate(65536, 4096, Kind::Engine)?;
                owned.push(commands);
                let image =
                    h.layout
                        .allocator
                        .allocate(golden.images[0].len() as u64, 4096, Kind::Engine)?;
                owned.push(image);
                let mmio = h.layout.allocator.allocate(4096, 4096, Kind::Engine)?;
                owned.push(mmio);
                for (va, a) in [(COMMAND, commands), (IMAGE, image), (golden.buffers[3].va, mmio)] {
                    context.map(
                        &mut h.layout.allocator,
                        &mut VmIo {
                            regs: h.regs,
                            total: h.total,
                        },
                        va,
                        a,
                        flags,
                    )?;
                }
                pages = Some(ManuallyDrop::new(system_dma::Pages::new(
                    1 + READBACK_BYTES / 4096,
                    &system_dma::translation_status()?,
                )?));
                let dma = pages.as_ref().unwrap();
                context.map_system(
                    &mut h.layout.allocator,
                    &mut VmIo {
                        regs: h.regs,
                        total: h.total,
                    },
                    TARGET,
                    &(0..1 + READBACK_BYTES / 4096).map(|i| dma.address(i)).collect::<Vec<_>>(),
                )?;
                for offset in (0..65536).step_by(4096) {
                    words(h.regs, h.total, commands.range.start + offset, &[0; 1024])?;
                }
                if golden.patches.len() * 8 > mmio.range.size as usize {
                    return Err("GR private MMIO list exceeds backing");
                }
                for offset in (0..mmio.range.size).step_by(4) {
                    words(h.regs, h.total, mmio.range.start + offset, &[0])?;
                }
                for (i, patch) in golden.patches.iter().enumerate() {
                    words(h.regs, h.total, mmio.range.start + i as u64 * 8, patch)?;
                }
                // gf100_gr_chan_bind (MIT gf100.c:331-338) copies the golden bytes and fills only the
                // internal-firmware header: count and MMIO VA >> 8 at offsets 0/4.
                let mut data = golden.runnable.clone();
                data[..256].fill(0);
                data[..4].copy_from_slice(&(golden.patches.len() as u32).to_le_bytes());
                data[4..8].copy_from_slice(&((golden.buffers[3].va >> 8) as u32).to_le_bytes());
                for (i, w) in data.chunks_exact(4).enumerate() {
                    words(
                        h.regs,
                        h.total,
                        image.range.start + i as u64 * 4,
                        &[u32::from_le_bytes(w.try_into().unwrap())],
                    )?;
                }
                // Packed 512-byte USERD slots share a BAR page, as in M6.4.
                // MIT FIFO gk104.c:82-118: RAMFC contains the physical slot,
                // 0xe8 contains CHID, and USERD.size is 0x200.
                let userd = userd.unwrap_or(commands.range.start + USERD);
                let instance = context.space().instance.range.start;
                for (offset, value) in [
                    (0x08, userd as u32),
                    (0x0c, (userd >> 32) as u32),
                    (0x10, 0xface),
                    (0x30, 0xfffff902),
                    (0x48, COMMAND as u32),
                    (0x4c, 9 << 16),
                    (0x84, 0x20400000),
                    (0x94, 0x30000fff),
                    (0x9c, 0x100),
                    (0xac, 0x1f),
                    (0xe4, 0x20),
                    (0xe8, id),
                    (0xb8, 0xf8000000),
                    (0xf8, 0x10003080),
                    (0xfc, 0x10000010),
                ] {
                    words(h.regs, h.total, instance + offset, &[value])?;
                }
                // gk104_ectx_bind selects 0x210 for GR and sets bit 2 in the VA.
                words(
                    h.regs,
                    h.total,
                    instance + 0x210,
                    &[(IMAGE | 4) as u32, (IMAGE >> 32) as u32],
                )?;
                words(h.regs, h.total, commands.range.start + RUNLIST, &[id, 0])?;
                Ok((commands, image, mmio, userd, instance))

            })();
            let (commands, image, mmio, userd, instance) = match built {
                Ok(parts) => parts,
                Err(error) => {
                    // No binding/admission has occurred. Cancel partial VM
                    // publication before dropping pins or releasing storage.
                    context.cancel_unsubmitted()?;
                    context.retire(&mut h.layout.allocator, &mut VmIo { regs: h.regs, total: h.total })?;
                    for a in owned { h.layout.allocator.release(a)?; }
                    if let Some(mut dma) = pages {
                        // SAFETY: the unsubmitted VM was detached above.
                        unsafe { ManuallyDrop::drop(&mut dma); }
                    }
                    return Err(error);
                }
            };
            let pages = pages.unwrap();
            let epoch = crate::arch_impl::x86_64::timer::rdtsc() | 1;
            let old = [
                h.regs.read(0x2254),
                h.regs.read(0x2140),
                enabled,
                h.regs.read(0x2630),
                h.regs.read(0x800004 + id as usize * 8),
                h.regs.read(0x200),
            ];
            let empty = Observation {
                value: 0,
                epoch: 0,
                consumed: false,
                elapsed_us: 0,
                accepted: false,
            };
            let release = Release {
                target: TARGET,
                poison: 0,
                nonce: 0,
                observed: 0,
                epoch: 0,
                elapsed_us: 0,
            };
            let b = 0x40000 + pbdma * 0x2000;
            Ok(Self {
                context,
                commands,
                image,
                mmio,
                userd,
                second: None,
                pages,
                pbdma,
                bar: h.console.pointer - displacement,
                bar_inst,
                bar_dir,
                pte,
                old,
                old_pbdma: [0x13c, 0x10c, 0x14c, 0x12c].map(|o| h.regs.read(b + o)),
                bound: false,
                admitted: false,
                alias: false,
                quiesced: false,
                preempt_error: None,
                next_sequence: 6,
                copy: None,
                report: Report {
                    identity: Identity {
                        id,
                        epoch,
                        instance,
                        top,
                        engine,
                        runlist,
                        bind: 0,
                        state: 0,
                        current_context: 0,
                    },
                    releases: [release; 2],
                    withheld: Withheld {
                        poison: 85,
                        observation: empty,
                    },
                    stale: Stale {
                        nonce: 0,
                        observation: empty,
                    },
                    faults: [[0x400100, 0], [0x400108, 0], [0x259c, 0]],
                    runlist_count: 1,
                    binding: 0,
                },
            })
        }
        pub(in crate::gk208::gr) fn activate(&mut self, h: &mut Hardware<'_>) -> Result<(), &'static str> {
            if self.report.identity.id != 0 || self.bound || self.quiesced {
                return Err("GR runlist owner unavailable");
            }
            let c = self.report.identity;
            // One BAR page, two distinct aliases at SLOT + CHID * 0x200.
            self.alias = true;
            words(h.regs, h.total, self.pte,
                &[((self.userd >> 8) | 1) as u32, 0])?;
            modeset::activate_bar1(h.regs, self.bar_inst, self.bar_dir)?;
            h.device.enable_bus_master();
            h.regs.write(0x2140, 0);
            h.regs.mask(0x200, 0x100, 0x100);
            h.regs.mask(0x204, 1 << self.pbdma, 1 << self.pbdma);
            let b = 0x40000 + self.pbdma * 0x2000;
            h.regs.mask(b + 0x13c, 0x10000100, 0);
            for (offset, value) in [(0x108, u32::MAX), (0x10c, 0),
                (0x148, u32::MAX), (0x14c, 0), (0x12c, 0xf4240)] {
                h.regs.write(b + offset, value);
            }
            h.regs.write(0x2254, 0x10000000 | (SLOT >> 12) as u32);
            h.regs.mask(0x2630, 1 << c.runlist, 1 << c.runlist);
            self.activate_channel(h)?;
            let mut entries = alloc::vec![c.id, 0];
            if let Some(second) = self.second.as_mut() {
                second.activate_channel(h)?;
                entries.extend([second.report.identity.id, 0]);
            }
            // MIT FIFO gk104.c:430-456: entries are {CHID, 0}; count
            // belongs to the runlist submission, not to an individual channel.
            words(h.regs, h.total, self.commands.range.start + RUNLIST, &entries)?;
            modeset::bar_flush(h.regs)?;
            h.regs.write(0x2270, ((self.commands.range.start + RUNLIST) >> 12) as u32);
            h.regs.write(0x2274, (c.runlist << 20) | (entries.len() as u32 / 2));
            h.regs.mask(0x2630, 1 << c.runlist, 0);
            register_wait(h.regs, 0x2284 + c.runlist as usize * 8, 0x100000, 0, BOUND_US)
        }
        fn activate_channel(&mut self, h: &mut Hardware<'_>) -> Result<(), &'static str> {
            let c = self.report.identity;
            self.quiesced = false;
            if !self.admitted {
                // SAFETY: Context::map retains mapping pins before channel publication.
                unsafe { self.context.admit_device()?; }
                self.admitted = true;
            }
            let ch = c.id as usize * 8;
            h.regs.mask(0x800004 + ch, 0xf0000, c.runlist << 16);
            self.bound = true;
            h.regs.write(0x800000 + ch, 0x80000000 | (c.instance >> 12) as u32);
            h.regs.mask(0x800004 + ch, 0x400, 0x400);
            Ok(())
        }
        fn issue(
            &self,
            h: &mut Hardware<'_>,
            sequence: u32,
            poison: u32,
            epoch: u64,
            nonce: u32,
            release: bool,
            budget: u64,
        ) -> Result<Observation, &'static str> {
            let command = commands(TARGET, epoch, nonce, release, sequence)?;
            self.issue_words(h, sequence, poison, nonce, budget, &command, false)
        }
        fn issue_words(
            &self, h: &mut Hardware<'_>, sequence: u32, poison: u32,
            nonce: u32, budget: u64, command: &[u32], stop_on_trap: bool,
        ) -> Result<Observation, &'static str> {
            // SAFETY: this retained WB DMA page is private, and the preceding
            // submission has consumed its stream before the next CPU poison.
            unsafe {
                core::ptr::write_bytes(self.pages.va(0) as *mut u8, poison as u8, 4096);
                (self.pages.va(0) as *mut u32).write_volatile(poison);
                ((self.pages.va(0) + 4) as *mut u32).write_volatile(0);
                ((self.pages.va(0) + 8) as *mut u32).write_volatile(0);
            }
            self.pages.publish();
            if !self.bound || self.quiesced || !(1..512).contains(&sequence)
                || command.is_empty() || command.len() * 4 > 16384 {
                return Err("GR command slot unavailable");
            }
            // One immutable slot, reused only after the preceding stream was
            // consumed and its engine receipt observed by the caller. A draw
            // exceeds the old 256-byte stride; keep it beyond USERD/runlist.
            let offset = 16384;
            words(
                h.regs,
                h.total,
                self.commands.range.start + offset,
                &command,
            )?;
            words(
                h.regs,
                h.total,
                self.commands.range.start + u64::from(sequence - 1) * 8,
                &[
                    (COMMAND + offset) as u32,
                    ((command.len() as u32) << 10) | 0x100,
                ],
            )?;
            modeset::bar_flush(h.regs)?;
            // SAFETY: the owned USERD page's WC BAR1 alias is installed above.
            unsafe {
                ((self.bar + SLOT as usize + self.report.identity.id as usize * 512 + 0x8c) as *mut u32).write_volatile(sequence);
            }
            crate::gpu_cache::drain_wc();
            let _ = h.regs.read(0x2254);
            let mut monitor = Monitor {
                session: self,
                regs: h.regs,
                total: h.total,
                sequence,
                stop_on_trap,
            };
            if budget < BOUND_US {
                // A cold context restore gets the normal engine bound before
                // the negative-control observation window starts.
                let start = monitor.now_us();
                while !monitor.snapshot()?.2 {
                    if monitor.now_us().saturating_sub(start) >= BOUND_US {
                        return Err("GR control stream not consumed; backing retained");
                    }
                    monitor.relax();
                }
            }
            let sample = wait(&mut monitor, self.report.identity.epoch, nonce, budget)?;
            if !sample.consumed {
                return Err("GR stream not consumed; backing retained");
            }
            Ok(sample)
        }
        pub(in crate::gk208::gr) fn bind_shaders(
            &mut self, h: &mut Hardware<'_>, code_address: u64,
            receipt: &mut super::super::binding::Receipt,
        ) -> Result<(), &'static str> {
            use super::super::binding;
            receipt.before = binding::TRAP_REGISTERS.map(|a| h.regs.read(a));
            let result = (|| {
                binding::check_traps(receipt.before)?;
                if !self.bound || self.quiesced {
                    return Err("shader binding requires the active GR channel");
                }
                let epoch = self.report.identity.epoch;
                let nonce = receipt_nonce(epoch, true);
                receipt.target = TARGET;
                receipt.epoch = epoch;
                receipt.nonce = nonce;
                let command = binding::commands(code_address, TARGET, epoch, nonce, 5)?;
                let sample = self.issue_words(h, 5, 85, nonce, BOUND_US, &command, true)?;
                receipt.observation = Some(sample);
                if !sample.accepted { return Err("shader binding release not observed"); }
                Ok(())
            })();
            // Read even after a submission error, before quiesce/reset.
            receipt.after = binding::TRAP_REGISTERS.map(|a| h.regs.read(a));
            binding::check_traps(receipt.after)?;
            result
        }
        /// Append a fresh ordinary mapping after bind_shaders' receipt. The
        /// allocation is registered before any fallible publication operation.
        pub(in crate::gk208::gr) fn allocate_draw(
            &mut self, h: &mut Hardware<'_>, name: &'static str, bytes: u64, alignment: u64,
        ) -> Result<super::super::context::Buffer, &'static str> {
            if !self.bound || self.quiesced { return Err("draw mapping requires active GR"); }
            if alignment < 4096 || !alignment.is_power_of_two() {
                return Err("invalid draw allocation alignment");
            }
            let va = h.next_va.checked_add(alignment - 1)
                .ok_or("draw VA alignment overflow")? & !(alignment - 1);
            let allocation = h.layout.allocator.allocate(bytes, alignment, Kind::Engine)?;
            h.next_va = va.checked_add(allocation.range.size + 4096).ok_or("draw VA overflow")?;
            h.backing.push((va, allocation));
            // SAFETY: bind_shaders returned an accepted engine receipt, and
            // subsequent uploads/draws are serialized to the same boundary.
            unsafe {
                self.context.map_idle(&mut h.layout.allocator,
                    &mut VmIo { regs: h.regs, total: h.total }, va, allocation,
                    Flags { volatile: true, ..Flags::default() })?;
            }
            Ok(super::super::context::Buffer {
                spec: super::super::context::Spec { name, bytes, align: alignment }, va,
            })
        }
        fn sequence(&mut self) -> Result<(u32, u32), &'static str> {
            let sequence = self.next_sequence;
            if sequence >= 512 { return Err("diagnostic GR ring exhausted"); }
            self.next_sequence += 1;
            let nonce = receipt_nonce(self.report.identity.epoch, true).wrapping_add(sequence);
            if nonce == 0 { return Err("draw receipt nonce overflow"); }
            Ok((sequence, nonce))
        }
        fn prepare_copy(&mut self, h: &mut Hardware<'_>) -> Result<(), &'static str> {
            if self.copy.is_some() { return Ok(()); }
            // GK208 TOP CE2 type 3 shares GR's runlist. No CE0 channel or
            // USERD alias may replace this retained FECS context. MIT Mesa
            // nvc0_screen.c:1080-1102 binds A0B5 on the graphics channel.
            let (mut engine, mut runlist, mut reset) = (None, None, None);
            let mut selected = None;
            for &w in &self.report.identity.top {
                if w & 3 == 2 {
                    if w & 32 != 0 { engine = Some((w >> 26) & 15); }
                    if w & 16 != 0 { runlist = Some((w >> 21) & 15); }
                    if w & 4 != 0 { reset = Some((w >> 9) & 31); }
                }
                if w != 0 && w & 0x80000000 == 0 {
                    if w & 3 == 3 && (w & 0x7ffffffc) >> 2 == 3
                        && runlist == Some(self.report.identity.runlist) {
                        selected = engine.zip(reset);
                        break;
                    }
                    engine = None; runlist = None; reset = None;
                }
            }
            let (engine, reset) = selected.ok_or("GR-runlist CE2 absent")?;
            // MIT gk104 CE: register base 0x104000 + inst * 0x1000.
            let base = 0x106000;
            // MIT nouveau mc/base.c:nvkm_mc_enable uses the TOP reset
            // mask before engine access. A disabled CE returns PRI errors,
            // not interrupt status; retain restoration state before refusal.
            let old_enable = h.regs.read(0x200) & (1 << reset);
            h.regs.mask(0x200, 1 << reset, 1 << reset);
            if h.regs.read(0x200) & (1 << reset) == 0 {
                return Err("draw CE2 enable did not latch");
            }
            self.copy = Some(DrawCopy { base, engine, reset,
                old_irq: h.regs.read(base + 0x904), old_enable });
            h.regs.write(base + 0x904, 0);
            if h.regs.read(base + 0x908) & 7 != 0 || h.regs.read(0x259c) != 0 {
                return Err("draw CE2 inherited fault");
            }
            Ok(())
        }
        /// Borrow the display owner's existing allocation through reset/drain.
        pub(in crate::gk208::gr) fn map_scanout(&mut self, h: &mut Hardware<'_>) -> Result<u64, &'static str> {
            if !self.bound || self.quiesced { return Err("scanout mapping requires active GR"); }
            let allocation = h.layout.objects[1].allocation;
            let va = h.next_va;
            h.next_va = va.checked_add(allocation.range.size + 4096).ok_or("scanout VA overflow")?;
            // SAFETY: the last draw/readback receipt completed; no submission
            // races this owner. The mapping pins display storage through reset.
            unsafe {
                self.context.map_idle(&mut h.layout.allocator,
                    &mut VmIo { regs: h.regs, total: h.total }, va, allocation,
                    Flags { volatile: true, ..Flags::default() })?;
            }
            Ok(va)
        }
        pub(in crate::gk208::gr) fn copy_rect(
            &mut self, h: &mut Hardware<'_>, rect: crate::gk208::copy::Rect,
        ) -> Result<(), &'static str> {
            self.prepare_copy(h)?;
            let (sequence, nonce) = self.sequence()?;
            let mut command = crate::gk208::copy::encode(rect, TARGET, self.report.identity.epoch, nonce)?;
            // A06F SET_REFERENCE (MIT cla06f.h:125) certifies stream
            // consumption; the CE epoch/nonce release certifies the transfer.
            command.extend([0x20010014, sequence]);
            let sample = self.issue_words(h, sequence, 85, nonce, BOUND_US, &command, true)?;
            if !sample.accepted { return Err("draw CE release not observed"); }
            Ok(())
        }
        fn transfer(
            &mut self, h: &mut Hardware<'_>, source: u64, target: u64, bytes: usize,
        ) -> Result<(), &'static str> {
            self.copy_rect(h, crate::gk208::copy::Rect {
                src: source, dst: target, width: bytes as u32, height: 1,
                src_pitch: bytes as u32, dst_pitch: bytes as u32,
            })
        }
        pub(in crate::gk208::gr) fn upload(
            &mut self, h: &mut Hardware<'_>, va: u64, data: &[u8],
        ) -> Result<(), &'static str> {
            if data.is_empty() || data.len() > 16384 { return Err("draw upload extent"); }
            for (i, chunk) in data.chunks(COPY_BYTES).enumerate() {
                // SAFETY: page 1 is owned coherent staging; prior CE receipt
                // was observed before it can be overwritten for another chunk.
                unsafe { core::ptr::copy_nonoverlapping(chunk.as_ptr(), self.pages.va(1) as *mut u8, chunk.len()); }
                self.pages.publish();
                self.transfer(h, TRANSFER, va + (i * COPY_BYTES) as u64, chunk.len())?;
            }
            Ok(())
        }
        pub(in crate::gk208::gr) fn readback(
            &mut self, h: &mut Hardware<'_>, va: u64, bytes: usize,
        ) -> Result<[Vec<u8>; 2], &'static str> {
            if bytes == 0 || bytes > 16 << 20 { return Err("draw readback extent"); }
            let mut images = [alloc::vec![0; bytes], alloc::vec![0; bytes]];
            for (index, poison) in [0x55, 0xaa].into_iter().enumerate() {
                for start in (0..bytes).step_by(READBACK_BYTES) {
                    let count = READBACK_BYTES.min(bytes - start);
                    // SAFETY: page 1 remains owned and the preceding CE release
                    // completed before this complementary destination poison.
                    for i in 1..=count.div_ceil(4096) {
                        unsafe { core::ptr::write_bytes(self.pages.va(i) as *mut u8, poison, 4096); }
                    }
                    self.pages.publish();
                    self.transfer(h, va + start as u64, TRANSFER, count)?;
                    crate::gpu_observation::read(&*self.pages, 4096, &mut images[index][start..start + count]);
                }
            }
            Ok(images)
        }
        pub(in crate::gk208::gr) fn draw(
            &mut self, h: &mut Hardware<'_>, mut draw: super::super::draw::Draw,
            receipt: &mut super::super::binding::Receipt,
        ) -> Result<(), &'static str> {
            use super::super::{binding, draw as encoder};
            receipt.before = binding::TRAP_REGISTERS.map(|a| h.regs.read(a));
            let result = (|| {
                binding::check_traps(receipt.before)?;
                let (sequence, nonce) = self.sequence()?;
                draw.report_va = TARGET; draw.epoch = self.report.identity.epoch; draw.nonce = nonce;
                receipt.target = TARGET; receipt.epoch = draw.epoch; receipt.nonce = nonce;
                let mut command = encoder::commands(draw)?;
                command.extend([0x20010014, sequence]);
                let observation = self.issue_words(h, sequence, 85, nonce, BOUND_US, &command, true)?;
                receipt.observation = Some(observation);
                if !observation.accepted { return Err("draw engine release not observed"); }
                Ok(())
            })();
            receipt.after = binding::TRAP_REGISTERS.map(|a| h.regs.read(a));
            binding::check_traps(receipt.after)?;
            result
        }
        pub(in crate::gk208::gr) fn execute(
            &mut self,
            h: &mut Hardware<'_>,
        ) -> Result<(), &'static str> {
            let epoch = self.report.identity.epoch;
            let nonce = receipt_nonce(epoch, false);
            self.report.withheld.observation = self.issue(h, 1, 85, epoch, nonce, false, 10000)?;
            if self.report.withheld.observation.accepted || self.report.withheld.observation.value != 85 {
                return Err("GR withheld release control failed");
            }
            let first = self.issue(h, 2, 85, epoch, nonce, true, BOUND_US)?;
            self.report.releases[0] = Release {
                target: TARGET,
                poison: 85,
                nonce,
                observed: first.value,
                epoch: first.epoch,
                elapsed_us: first.elapsed_us,
            };
            if !first.accepted {
                return Err("GR first release not accepted");
            }
            // Re-poison only after an engine-ordered receipt. On a missing
            // receipt retain the raw failure, stop submission and drain below;
            // a delayed old release must not satisfy the second poison pass.
            if first.accepted {
                let stale = self.issue(h, 3, 170, epoch - 1, nonce, true, 10000)?;
                self.report.stale = Stale {
                    nonce,
                    observation: stale,
                };
                if !stale.accepted && stale.value == nonce && stale.epoch == epoch - 1 {
                    let second = self.issue(h, 4, 170, epoch, nonce, true, BOUND_US)?;
                    if !second.accepted { return Err("GR second release not accepted"); }
                    self.report.releases[1] = Release {
                        target: TARGET,
                        poison: 170,
                        nonce,
                        observed: second.value,
                        epoch: second.epoch,
                        elapsed_us: second.elapsed_us,
                    };
                } else {
                    return Err("GR stale release control failed");
                }
            }
            self.report.identity.bind = h.regs.read(0x800000 + self.report.identity.id as usize * 8);
            self.report.identity.state = h.regs.read(0x800004 + self.report.identity.id as usize * 8);
            self.report.identity.current_context = h.regs.read(0x409b00);
            for pair in &mut self.report.faults {
                pair[1] = h.regs.read(pair[0] as usize);
            }
            Ok(())
        }
        /// Remove the whole owned runlist before restoring shared FIFO state.
        /// Any reset, drain, unbind or alias error forbids pair reclamation.
        pub(in crate::gk208::gr) fn quiesce(
            &mut self, regs: &mut Registers, total: u64,
        ) -> Result<(), &'static str> {
            if self.quiesced { return Ok(()); }
            let c = self.report.identity;
            let mut failure = None;
            let active = self.bound || self.second.as_ref().is_some_and(|s| s.bound);
            if active {
                regs.mask(0x2630, 1 << c.runlist, 1 << c.runlist);
                // Disable both before preempt: fallback reset stops the GR engine.
                for s in core::iter::once(&*self).chain(self.second.as_deref()) {
                    if s.bound { regs.mask(0x800004 + s.report.identity.id as usize * 8, 0x800, 0x800); }
                }
                if let Err(e) = self.quiesce_channel(regs) { failure.get_or_insert(e); }
                if let Some(second) = self.second.as_mut() {
                    if let Err(e) = second.quiesce_channel(regs) { failure.get_or_insert(e); }
                }
                regs.write(0x2270, ((self.commands.range.start + RUNLIST) >> 12) as u32);
                regs.write(0x2274, c.runlist << 20);
                for (address, mask, budget) in [
                    (0x2284 + c.runlist as usize * 8, 0x100000, BOUND_US),
                    (0x3080 + self.pbdma * 4, 0xe000, BOUND_US),
                    (0x2640 + c.engine as usize * 8, 0x80000000, 100000),
                ] {
                    if let Err(e) = register_wait(regs, address, mask, 0, budget) { failure.get_or_insert(e); }
                }
            }
            // Unbind the owned pair even after an earlier error.
            let mut second = self.second.take();
            for s in core::iter::once(&mut *self).chain(second.as_deref_mut()) {
                if active && s.bound {
                    if let Some(copy) = &s.copy {
                        if let Err(e) = register_wait(regs, 0x2640 + copy.engine as usize * 8, 0x80000000, 0, 100000) {
                            failure.get_or_insert(e);
                        }
                    }
                    let ch = s.report.identity.id as usize * 8;
                    regs.write(0x800000 + ch, 0);
                    s.report.binding = regs.read(0x800000 + ch);
                    s.report.runlist_count = regs.read(0x2274) & 0xfffff;
                    if s.report.binding != 0 { failure.get_or_insert("GR unbind failed; backing retained"); }
                    else { s.bound = false; }
                }
                regs.write(0x800004 + s.report.identity.id as usize * 8, s.old[4]);
            }
            self.second = second;
            if self.alias {
                let clear = words(regs, total, self.pte, &[0, 0])
                    .and_then(|()| modeset::activate_bar1(regs, self.bar_inst, self.bar_dir));
                if let Err(e) = clear { failure.get_or_insert(e); }
                else { self.alias = false; }
            }
            let b = 0x40000 + self.pbdma * 0x2000;
            for (offset, value) in [0x13c, 0x10c, 0x14c, 0x12c].into_iter().zip(self.old_pbdma) {
                regs.write(b + offset, value);
            }
            regs.write(0x2254, self.old[0]);
            regs.write(0x2140, self.old[1]);
            regs.write(0x204, self.old[2]);
            regs.mask(0x2630, 1 << c.runlist, self.old[3] & (1 << c.runlist));
            regs.mask(0x200, 0x100, self.old[5] & 0x100);
            if let Some(second) = self.second.as_ref() {
                if let Some(copy) = &second.copy {
                    regs.write(copy.base + 0x904, copy.old_irq);
                    regs.mask(0x200, 1 << copy.reset, copy.old_enable);
                }
            }
            if let Some(copy) = &self.copy {
                regs.write(copy.base + 0x904, copy.old_irq);
                regs.mask(0x200, 1 << copy.reset, copy.old_enable);
            }
            if let Some(e) = failure { return Err(e); }
            if let Some(second) = self.second.as_mut() { second.quiesced = true; }
            self.quiesced = true;
            Ok(())
        }
        fn quiesce_channel(&mut self, regs: &mut Registers) -> Result<(), &'static str> {
            if !self.bound { return Ok(()); }
            let c = self.report.identity;
            regs.write(0x2634, c.id);
            if let Err(error) = register_wait(regs, 0x2634, 0x100000, 0, BOUND_US) {
                self.preempt_error = Some(error);
                let enable = regs.read(0x200) & 0x1000;
                let reset = super::super::ctxctl::reset(regs).map_err(super::super::hardware_error);
                regs.mask(0x200, 0x1000, enable);
                reset?;
                if regs.read(0x259c) & 1 != 0
                    && u64::from(regs.read(0x2800)) << 12 == c.instance {
                    // MIT FIFO gf100.c:696-733 and gk104.c:404-418.
                    regs.write(0x259c, 1);
                    if regs.read(0x259c) == 0 {
                        regs.write(0x262c, 1 << c.runlist);
                        regs.mask(0x2630, 1 << c.runlist, 0);
                    }
                }
            }
            Ok(())
        }
        pub(in crate::gk208::gr) fn preempt_result(&self) -> Result<(), &'static str> {
            self.preempt_error.or_else(|| self.second.as_ref().and_then(|s| s.preempt_error)).map_or(Ok(()), Err)
        }
        pub(in crate::gk208::gr) fn report(&self) -> Report {
            self.report
        }
        /// Called only after Hardware::finish confirms GR reset. Retire after
        /// reset so FECS cannot later save through its old current-context word.
        pub(in crate::gk208::gr) fn finish(
            mut self,
            regs: &mut Registers,
            layout: &mut memory::Layout,
            total: u64,
        ) -> Result<(), &'static str> {
            if !self.quiesced {
                return Err("GR retirement before FIFO unwind");
            }
            if let Some(second) = self.second.take() {
                second.finish_channel(regs, layout, total)?;
            }
            self.finish_channel(regs, layout, total)
        }
        fn finish_channel(
            mut self, regs: &mut Registers, layout: &mut memory::Layout, total: u64,
        ) -> Result<(), &'static str> {
            if !self.quiesced { return Err("GR retirement before pair unwind"); }
            // SAFETY: reset has stopped GR; quiesce removed and drained FIFO.
            unsafe {
                self.context.confirm_reset();
            }
            self.context
                .retire(&mut layout.allocator, &mut VmIo { regs, total })?;
            layout.allocator.release(self.commands)?;
            layout.allocator.release(self.image)?;
            layout.allocator.release(self.mmio)?;
            // SAFETY: GR reset and PFIFO drain precede system-page reclamation.
            unsafe {
                ManuallyDrop::drop(&mut self.pages);
            }
            Ok(())
        }
    }
    struct Monitor<'a> {
        session: &'a Session,
        regs: &'a mut Registers,
        total: u64,
        sequence: u32,
        stop_on_trap: bool,
    }
    impl Poll for Monitor<'_> {
        fn snapshot(&mut self) -> Result<(u32, u64, bool), &'static str> {
            if self.stop_on_trap {
                let words = super::super::binding::TRAP_REGISTERS.map(|a| self.regs.read(a));
                super::super::binding::check_traps(words)?;
                let p = self.session.pbdma * 0x2000;
                if self.regs.read(0x259c) != 0 || self.regs.read(0x40108 + p) != 0
                    || self.regs.read(0x40148 + p) != 0
                    || self.session.copy.as_ref().is_some_and(|c| self.regs.read(c.base + 0x908) & 7 != 0) {
                    return Err("draw FIFO/CE fault; backing retained");
                }
            }
            let s = self.session;
            s.pages.observe();
            // SAFETY: coherent observation of the owned page's three words.
            let (value, lo, hi) = unsafe {
                let p = s.pages.va(0) as *const u32;
                (
                    p.read_volatile(),
                    p.add(1).read_volatile(),
                    p.add(2).read_volatile(),
                )
            };
            let b = s.pbdma * 0x2000;
            let current = self.regs.read(0x40120 + b) & 0x2fff == 0x2000 | self.session.report.identity.id;
            let get = if current {
                self.regs.read(0x40014 + b)
            } else {
                read(self.regs, self.total, s.userd + 0x88)?
            };
            let consumed = current
                && get == self.sequence
                && self.regs.read(0x40028 + b) == self.sequence
                && self.regs.read(0x800000 + s.report.identity.id as usize * 8)
                    == 0x80000000 | (s.report.identity.instance >> 12) as u32;
            Ok((value, u64::from(lo) | (u64::from(hi) << 32), consumed))
        }
        fn now_us(&mut self) -> u64 {
            elapsed(0)
        }
        fn relax(&mut self) {
            self.regs.delay_us(10);
        }
    }
