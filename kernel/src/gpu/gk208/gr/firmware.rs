//! Source-built Falcon v5 images from the 7.1 toolchain; verified by build.rs.
//! Bytes are decoded as little-endian words without pointer alignment assumptions.

const fn words<const N: usize>(bytes: &[u8]) -> [u32; N] {
    assert!(bytes.len() == N * 4);
    let mut out = [0; N];
    let mut i = 0;
    while i < N {
        let j = i * 4;
        out[i] = u32::from_le_bytes([bytes[j], bytes[j + 1], bytes[j + 2], bytes[j + 3]]);
        i += 1;
    }
    out
}

