//! Prepared terminal access to the existing A06F/A197/A0B5 and 927D channels.
//! NVIDIA open-gpu-doc headers at 9fdf5c4 (MIT), notices above. The ordinary
//! writers are frozen by gpu::panic::Access; no lock, allocation, VM change,
//! normal request or reset is permitted below the preparation boundary.
use super::{memory, Registers};
use alloc::vec::Vec;
mod arch {
    pub fn counter() -> u64 {
        crate::arch_read_timestamp()
    }
}

/// A private PRAMIN accessor after the terminal drain. It deliberately does not
/// acquire Registers' ordinary selector lock, which this CPU may have stranded.
struct Terminal(usize);
impl memory::Access for Terminal {
    fn read(&mut self, r: usize) -> u32 {
        Registers(self.0).read(r)
    }
    fn write(&mut self, r: usize, v: u32) {
        Registers(self.0).write(r, v);
    }
}
fn read(q: &mut Terminal, total: u64, a: u64) -> Option<u32> {
    memory::Pramin::new(q, total).read(a).ok()
}
fn write(q: &mut Terminal, total: u64, a: u64, v: u32) -> bool {
    memory::Pramin::new(q, total).write(a, v).is_ok()
}
fn poll(deadline: u64, mut f: impl FnMut() -> bool) -> bool {
    while arch::counter() < deadline {
        if f() {
            return true;
        }
        core::hint::spin_loop();
    }
    false
}
fn flush(q: &Registers, deadline: u64) -> bool {
    q.write(0x70000, 1);
    poll(deadline, || q.read(0x70000) & 2 == 0)
}

pub(crate) struct Packet {
    address: u64,
    words: u32,
    nonce: u32,
}
pub(crate) struct Queue {
    pub registers: usize,
    pub total: u64,
    pub ring: u64,
    pub userd: u64,
    pub userd_bar: usize,
    pub pbdma: usize,
    pub ce_error: usize,
    pub channel: u32,
    pub instance: u64,
    pub report: u64,
    pub report_va: u64,
    pub epoch: u64,
    pub quarantine: u64,
    pub parking: Vec<u32>,
}
impl Queue {
    /// Preparation only: share the existing channel's retained code/VAB, and
    /// append engine-ordered epoch/nonce releases into a disjoint pinned slot.
    pub(crate) fn draw(&self, input: &[u32], nonce: u32) -> Result<Vec<u32>, &'static str> {
        let mut payload = super::encode::channel_words(input, self.quarantine)?;
        super::encode::channel_programs(&mut payload, &self.parking)?;
        let mut words = super::gr::channel::bind().to_vec();
        words.extend(payload);
        for (offset, value) in [
            (4, self.epoch as u32),
            (8, (self.epoch >> 32) as u32),
            (0, nonce),
        ] {
            words.extend(super::gr::channel::report(self.report_va + offset, value)?);
        }
        Ok(words)
    }
    pub(crate) fn packet(
        &self,
        address: u64,
        words: usize,
        nonce: u32,
    ) -> Result<Packet, &'static str> {
        if address & 3 != 0 || address >= 1 << 40 || words == 0 || words >= 1 << 21 {
            return Err("terminal packet extent");
        }
        Ok(Packet {
            address,
            words: words as u32,
            nonce,
        })
    }
    fn healthy(&self) -> bool {
        let r = Registers(self.registers);
        let p = self.pbdma * 0x2000;
        r.read(0x800000 + self.channel as usize * 8) == 0x80000000 | (self.instance >> 12) as u32
            && r.read(0x259c) == 0
            && r.read(0x40108 + p) == 0
            && r.read(0x40148 + p) == 0
            && r.read(self.ce_error) & 7 == 0
            && [0x400100, 0x400108, 0x400110, 0x400118]
                .iter()
                .all(|&a| r.read(a) == 0)
    }
    /// Hardware GP_GET follows the active PBDMA, or the retained USERD when
    /// descheduled, just as the normal channel monitor does.
    fn consumed(&self, put: u32) -> bool {
        let r = Registers(self.registers);
        let p = self.pbdma * 0x2000;
        if r.read(0x40120 + p) & 0x2fff == 0x2000 | self.channel {
            r.read(0x40014 + p) == put
        } else {
            read(&mut Terminal(self.registers), self.total, self.userd + 0x88) == Some(put)
        }
    }
    pub(crate) fn drain(&self, deadline: u64) -> bool {
        let Some(put) = read(&mut Terminal(self.registers), self.total, self.userd + 0x8c) else {
            return false;
        };
        put < 512 && poll(deadline, || self.healthy() && self.consumed(put))
    }
    /// One prepared stream at a time. An IB entry is reused after GP_GET reaches GP_PUT;
    /// normal command bytes and their receipts/backing are left intact.
    pub(crate) fn exec(&self, c: &Packet, deadline: u64) -> bool {
        if arch::counter() >= deadline || !self.healthy() {
            return false;
        }
        let mut io = Terminal(self.registers);
        let Some(put) = read(&mut io, self.total, self.userd + 0x8c) else {
            return false;
        };
        if put >= 512 || !poll(deadline, || self.consumed(put)) {
            return false;
        }
        // SAFETY: this is the private, pinned coherent report slot. Terminal
        // ownership excludes normal writers; each packet carries a fresh nonce.
        unsafe {
            core::ptr::write_bytes(self.report as *mut u8, 0, 16);
        }
        core::sync::atomic::fence(core::sync::atomic::Ordering::SeqCst);
        if !write(
            &mut io,
            self.total,
            self.ring + u64::from(put) * 8,
            c.address as u32,
        ) || !write(
            &mut io,
            self.total,
            self.ring + u64::from(put) * 8 + 4,
            (c.address >> 32) as u32 | c.words << 10 | 0x100,
        ) || !flush(&Registers(self.registers), deadline)
        {
            return false;
        }
        let next = (put + 1) % 512;
        // USERD's BAR1 alias notifies PFIFO; a PRAMIN store only updates
        // VRAM. This is the same retained WC aperture as normal publication.
        // SAFETY: preparation pins this channel's private mapped USERD slot;
        // the terminal latch excludes its normal producer and no mapping changes.
        unsafe { ((self.userd_bar + 0x8c) as *mut u32).write_volatile(next); }
        crate::gpu_cache::drain_wc();
        let _ = Registers(self.registers).read(0x2254);
        poll(deadline, || {
            let value = unsafe { (self.report as *const u32).read_volatile() };
            let lo = unsafe { ((self.report + 4) as *const u32).read_volatile() };
            let hi = unsafe { ((self.report + 8) as *const u32).read_volatile() };
            value == c.nonce
                && (u64::from(lo) | u64::from(hi) << 32) == self.epoch
                && self.healthy()
                && self.consumed(next)
        })
    }
}

pub(crate) struct Display {
    pub registers: usize,
    pub total: u64,
    pub push: u64,
    pub notifier: u64,
    pub head: u32,
    pub sor: u32,
    pub methods: Vec<(u32, u32)>,
    #[cfg(any(feature = "capture_panic_oracle", feature = "gpu_fault_acceptance"))]
    pub target: u32,
}
impl Display {
    pub(crate) fn prepare(surface: super::present::Surface) -> Result<Self, &'static str> {
        super::ce::terminal_display(surface)
    }
    pub(crate) fn bound(&self) -> bool {
        let r = Registers(self.registers);
        self.methods[..self.methods.len() - 2]
            .iter()
            .all(|&(method, value)| {
                r.read(0x640000 + method as usize) == value
                    && r.read(0x660000 + method as usize) == value
            })
            && r.read(0x61009c) == 0
            && r.read(0x616308 + self.head as usize * 0x800) & 0x111 == 1
            && r.read(0x61c004 + self.sor as usize * 0x800) & 0x80000001 == 1
            && r.read(0x61c030 + self.sor as usize * 0x800) & 0x10000000 == 0
    }
    pub(crate) fn show(&self, deadline: u64) -> bool {
        let r = Registers(self.registers);
        let mut io = Terminal(self.registers);
        let put = r.read(0x640000);
        if put > 2044 || arch::counter() >= deadline {
            return false;
        }
        // Append the prepared flip at the hardware-published cursor. A
        // stranded CPU's unpublished bytes are replaceable; prior methods
        // precede the jump. Do not wait on the ordinary EVO queue.
        for n in 0..4 {
            if !write(&mut io, self.total, self.notifier + n * 4, 0) {
                return false;
            }
        }
        if !write(&mut io, self.total, self.push + u64::from(put), 0x20000800)
            || !flush(&r, deadline) { return false; }
        // Methods were encoded into the reserved half-page at preparation.
        let end = 2048 + self.methods.len() as u32 * 8;
        r.write(0x640000, end);
        poll(deadline, || {
            read(&mut io, self.total, self.notifier).is_some_and(|v| v & 1 == 1)
                && r.read(0x640004) == end
                && self.bound()
        })
    }
}

/// Preparation only: map immutable command pages and retain their resource.
pub(crate) fn map_commands(
    backing: alloc::sync::Arc<crate::gpu::dma::Pages>,
) -> Result<(u64, super::resource::Hold), &'static str> {
    let pages: Vec<_> = (0..backing.count()).map(|i| backing.page_addr(i)).collect();
    super::ce::with_resources(|r, a, io| {
        let id = r.draw_buffer(a, io, backing.bytes() as u32)?;
        r.attach(a, io, id, backing.clone(), &pages, backing.bytes() as u64)?;
        let hold = r.hold(id)?;
        let address = r.address(id).ok_or("terminal commands absent")?;
        r.unref(id)?;
        Ok((address, hold))
    })
}
#[cfg(any(feature = "capture_panic_oracle", feature = "gpu_fault_acceptance"))]
pub(crate) fn readback(
    id: u32,
    backing: &alloc::sync::Arc<crate::gpu::dma::Pages>,
    pages: &[u64],
) -> Result<super::copy::Plan, &'static str> {
    super::ce::with_resources(|r, a, io| {
        let l = r.layout(id).ok_or("terminal target layout absent")?;
        let image = super::copy::Image {
            address: r.address(id).ok_or("terminal target absent")?,
            width: l.width,
            height: l.height,
            texel_bytes: l.texel_bytes,
            pitch: l.pitch,
            block_height: l.block_height,
            bytes: l.bytes,
        };
        let address = r.map_backing(a, io, id, backing, pages, backing.bytes() as u64)?;
        super::copy::readback(
            image,
            super::copy::Linear {
                address,
                bytes: backing.bytes() as u64,
                offset: 0,
                stride: l.width * 4,
            },
            [0, 0, l.width, l.height],
        )
    })
}
